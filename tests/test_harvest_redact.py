import numpy as np

from pipeline.crop import Detection
from pipeline.harvest.redact import (
    MIN_FACE_SIDE_PX,
    MIN_PLATE_W_PX,
    blur_kernel,
    redact_frame,
    vehicle_search_box,
)


class СписокДетектор:
    """Отдаёт заготовленные боксы: по одному списку на каждый вызов detect."""

    def __init__(self, сценарий: list[list[Detection]]) -> None:
        self.сценарий = list(сценарий)
        self.вызовы = 0

    def detect(self, image: np.ndarray) -> list[Detection]:
        self.вызовы += 1
        return self.сценарий.pop(0) if self.сценарий else []


def _кадр() -> np.ndarray:
    # Не однотонный: размытие однотонной области не меняет пиксели, и тест на
    # «лицо размыто» стал бы ложно-зелёным. Редкие точки блюр размазывает.
    кадр = np.full((400, 600, 3), 128, dtype=np.uint8)
    кадр[::3, ::3] = 255
    return кадр


МАШИНА = Detection(x=50.0, y=50.0, w=300.0, h=200.0, conf=0.9, cls=2)
НОМЕР = Detection(x=120.0, y=210.0, w=80.0, h=24.0, conf=0.9, cls=0)
ЛИЦО = Detection(x=400.0, y=60.0, w=40.0, h=40.0, conf=0.9, cls=0)


def test_ядро_размытия_нечётное_и_растёт() -> None:
    assert blur_kernel(30) == 15
    assert blur_kernel(300) % 2 == 1


def test_бокс_поиска_вокруг_машины_шире_на_15_процентов() -> None:
    x0, y0, x1, y1 = vehicle_search_box(
        Detection(x=100.0, y=100.0, w=100.0, h=50.0, conf=0.9, cls=2), 600, 400
    )
    assert (x0, y0, x1, y1) == (85, 92, 215, 158)


def test_бокс_поиска_обрезается_кадром() -> None:
    x0, y0, x1, y1 = vehicle_search_box(
        Detection(x=0.0, y=0.0, w=600.0, h=400.0, conf=0.9, cls=2), 600, 400
    )
    assert (x0, y0, x1, y1) == (0, 0, 600, 400)


def test_номер_заливается_сплошным_а_не_размывается() -> None:
    номера = СписокДетектор([[НОМЕР], []])
    итог = redact_frame(_кадр(), [МАШИНА], [номера], СписокДетектор([[], []]))
    assert итог.ok
    assert итог.plates == 1
    вокруг = итог.image[210:234, 120:200]
    assert int(вокруг.max()) == 0, "номер должен быть залит нулём, не размыт"


def test_заливка_номера_расширяется_за_бокс() -> None:
    """Символы выходят за тесный бокс детектора — заливка шире на PLATE_FILL_PAD."""
    номера = СписокДетектор([[НОМЕР], []])
    итог = redact_frame(_кадр(), [МАШИНА], [номера], СписокДетектор([[], []]))
    # столбец на 6 px левее бокса (80*0.15≈12) тоже должен быть залит
    assert int(итог.image[220, 112].max()) == 0


def test_номер_меньше_порога_игнорируется() -> None:
    мелкий = Detection(x=300.0, y=300.0, w=MIN_PLATE_W_PX - 2, h=6.0, conf=0.9, cls=0)
    номера = СписокДетектор([[мелкий]])
    итог = redact_frame(_кадр(), [МАШИНА], [номера], СписокДетектор([[]]))
    assert итог.ok
    assert итог.plates == 0
    assert np.array_equal(итог.image, _кадр())


def test_лицо_меньше_порога_игнорируется() -> None:
    мелкое = Detection(x=400.0, y=60.0, w=MIN_FACE_SIDE_PX - 4, h=MIN_FACE_SIDE_PX - 4,
                       conf=0.9, cls=0)
    итог = redact_frame(_кадр(), [МАШИНА], [СписокДетектор([[]])], СписокДетектор([[мелкое]]))
    assert итог.ok
    assert итог.faces == 0


def test_лицо_размывается_лестницей_а_не_заливается_сразу() -> None:
    лица = СписокДетектор([[ЛИЦО], []])
    итог = redact_frame(_кадр(), [МАШИНА], [СписокДетектор([[], []])], лица)
    assert итог.ok
    assert итог.faces == 1
    патч = итог.image[60:100, 400:440]
    assert int(патч.max()) > 0, "лицо размыто, не залито в ноль на первой ступени"
    assert not np.array_equal(патч, _кадр()[60:100, 400:440])


def test_ансамбль_объединяет_находки_двух_детекторов() -> None:
    номер_а = Detection(x=120.0, y=210.0, w=80.0, h=24.0, conf=0.9, cls=0)
    номер_б = Detection(x=400.0, y=210.0, w=80.0, h=24.0, conf=0.9, cls=0)
    д1 = СписокДетектор([[номер_а], [], [], []])
    д2 = СписокДетектор([[номер_б], [], [], []])
    итог = redact_frame(_кадр(), [МАШИНА], [д1, д2], СписокДетектор([[], []]))
    assert итог.ok
    assert итог.plates == 2
    assert int(итог.image[220, 130].max()) == 0
    assert int(итог.image[220, 430].max()) == 0


def test_номер_пробивающий_заливку_отбраковывает_кадр() -> None:
    номера = СписокДетектор([[НОМЕР], [НОМЕР], [НОМЕР], [НОМЕР]])
    итог = redact_frame(_кадр(), [МАШИНА], [номера], СписокДетектор([[], [], []]))
    assert not итог.ok


def test_чистый_кадр_не_меняется() -> None:
    исходник = _кадр()
    итог = redact_frame(исходник, [МАШИНА], [СписокДетектор([[]])], СписокДетектор([[]]))
    assert итог.ok
    assert итог.plates == 0 and итог.faces == 0
    assert np.array_equal(итог.image, исходник)


def test_номер_вне_боксов_машин_но_в_кадре_ловится_полнокадровым_проходом() -> None:
    """Фоновая машина без своего YOLO-бокса — номер всё равно должен уйти."""
    далёкий = Detection(x=500.0, y=20.0, w=60.0, h=18.0, conf=0.9, cls=0)
    номера = СписокДетектор([[далёкий], []])
    итог = redact_frame(_кадр(), [МАШИНА], [номера], СписокДетектор([[], []]))
    assert итог.ok
    assert итог.plates == 1
    assert int(итог.image[25, 520].max()) == 0

