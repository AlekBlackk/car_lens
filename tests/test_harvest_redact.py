import numpy as np

from pipeline.crop import Detection
from pipeline.harvest.redact import blur_kernel, redact, redaction_zone


class СценарныйДетектор:
    """Отдаёт заготовленные боксы по одному вызову на шаг лестницы замыва."""

    def __init__(self, сценарий: list[list[Detection]]) -> None:
        self.сценарий = list(сценарий)
        self.вызовы = 0

    def detect(self, image: np.ndarray) -> list[Detection]:
        self.вызовы += 1
        return self.сценарий.pop(0) if self.сценарий else []


def _кадр() -> np.ndarray:
    кадр = np.full((200, 300, 3), 128, dtype=np.uint8)
    кадр[15:35, 15:35] = 255
    return кадр


НОМЕР = Detection(x=100.0, y=150.0, w=60.0, h=20.0, conf=0.9, cls=0)


def test_ядро_размытия_растёт_с_боксом() -> None:
    assert blur_kernel(30) == 15, "нижняя планка держит мелкие боксы"
    assert blur_kernel(300) == 101
    assert blur_kernel(300) % 2 == 1, "ядро OpenCV обязано быть нечётным"


def test_зона_редакции_шире_кропа() -> None:
    """Номер, срезанный границей кропа, обязан попасть в зону детекции."""
    x0, y0, x1, y1 = redaction_zone(
        Detection(x=100.0, y=100.0, w=100.0, h=50.0, conf=0.9, cls=2), 300, 200
    )
    assert (x0, y0) == (90, 95)
    assert (x1, y1) == (210, 155)


def test_зона_не_вылезает_за_кадр() -> None:
    x0, y0, x1, y1 = redaction_zone(
        Detection(x=0.0, y=0.0, w=300.0, h=200.0, conf=0.9, cls=2), 300, 200
    )
    assert (x0, y0, x1, y1) == (0, 0, 300, 200)


def test_размытия_хватило() -> None:
    номера = СценарныйДетектор([[НОМЕР], []])
    лица = СценарныйДетектор([[], []])
    итог = redact(_кадр(), номера, лица)
    assert итог.ok
    assert итог.plates == 1
    assert номера.вызовы == 2, "детекция до замыва и проверка после"


def test_заливка_как_вторая_ступень() -> None:
    """Если после размытия детектор всё ещё видит номер, кадр не теряется сразу."""
    номера = СценарныйДетектор([[НОМЕР], [НОМЕР], []])
    лица = СценарныйДетектор([[], [], []])
    итог = redact(_кадр(), номера, лица)
    assert итог.ok
    assert номера.вызовы == 3


def test_кадр_отбраковывается_после_заливки() -> None:
    номера = СценарныйДетектор([[НОМЕР], [НОМЕР], [НОМЕР]])
    лица = СценарныйДетектор([[], [], []])
    итог = redact(_кадр(), номера, лица)
    assert not итог.ok, "замыв, который детектор пробивает, — это отбраковка кадра"


def test_чистый_кадр_не_меняется() -> None:
    исходник = _кадр()
    итог = redact(исходник, СценарныйДетектор([[]]), СценарныйДетектор([[]]))
    assert итог.ok
    assert итог.plates == 0 and итог.faces == 0
    assert np.array_equal(итог.image, исходник)


def test_лица_замываются_наравне_с_номерами() -> None:
    лица = СценарныйДетектор([[Detection(10.0, 10.0, 30.0, 30.0, 0.9, 0)], []])
    итог = redact(_кадр(), СценарныйДетектор([[], []]), лица)
    assert итог.ok
    assert итог.faces == 1
    assert not np.array_equal(итог.image[10:40, 10:40], _кадр()[10:40, 10:40])
