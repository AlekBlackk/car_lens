"""Тесты сырого ранжирования замера: `ranked_predictions` (§4 дизайна). Требуют torch."""

import pytest

pytest.importorskip("torch")

import torch
from torch import Tensor, nn
from torch.utils.data import DataLoader, TensorDataset

from training.evaluate import evaluate, ranked_predictions
from training.metrics import TOP_K
from training.model import ArcFaceHead, CarClassifier

# Классов шесть, а не пять: `evaluate` требует не меньше `TOP_K` выходов головы, а шестой
# класс не попадает в top-5 ни у одного кадра фикстуры — иначе `top5_model` был бы равен
# 1.0 по построению и регресса M-1.2 в нём не увидеть.
ЧИСЛО_КЛАССОВ = 6
УСТРОЙСТВО = torch.device("cpu")
# top-3 замера Р-11: `k`, отличный от `TOP_K`, — весь смысл вынесенной функции.
K = 3

# «Кадр» здесь — сразу эмбеддинг: голова с единичным весом отдаёт логитом косинус с ортом
# класса, а он монотонен по соответствующей компоненте. Настоящий бэкбон дал бы случайные
# логиты, и ожидаемый порядок пришлось бы считать тем же кодом, который проверяется.
# Компоненты внутри кадра попарно различны — ранжирование строгое, ничьих нет.
ЭМБЕДДИНГИ = torch.tensor(
    [
        [0.1, 0.9, 0.5, 0.2, 0.3, 0.4],
        [0.4, 0.2, 0.1, 0.8, 0.6, 0.3],
        [0.7, 0.6, 0.5, 0.4, 0.3, 0.05],
    ]
)
# Метка кадра 0 — второй по логиту (попадание в top-5, но не в top-1), кадра 1 — его argmax
# (top-1), кадра 2 — последний из шести (промах даже по top-5). Отсюда 1/3 и 2/3 ниже.
# Argmax кадра 1 (класс 3) — не минимальный индекс в его top-5: иначе `top1_model` совпал бы
# и у кода, который отдаёт индексы по возрастанию номера класса, а не по убыванию логита.
МЕТКИ = torch.tensor([2, 3, 5])
# Выписано руками по `ЭМБЕДДИНГИ`: ожидание обязано быть независимым от кода замера.
ОЖИДАЕМОЕ_РАНЖИРОВАНИЕ = [
    [1, 2, 5, 4, 3, 0],
    [3, 4, 0, 5, 1, 2],
    [0, 1, 2, 3, 4, 5],
]
ИНДЕКС_КЛАССОВ = {
    0: "acura__rl",
    1: "acura__tl",
    2: "bmw__x5",
    3: "chevrolet__corvette",
    4: "chevrolet__express",
    5: "ford__f150",
}
МАРКИ_КЛАССОВ: dict[int, str | None] = {
    0: "Acura",
    1: "Acura",
    2: "BMW",
    3: "Chevrolet",
    4: "Chevrolet",
    5: "Ford",
}


class ВекторныйБэкбон(nn.Module):  # type: ignore[misc]
    """Бэкбон-подстава: «кадр» загрузчика уже вектор признаков и отдаётся как есть."""

    def __init__(self) -> None:
        super().__init__()
        self.num_features = ЧИСЛО_КЛАССОВ

    def forward(self, image: Tensor) -> Tensor:
        return image


def подставной_замер() -> tuple[CarClassifier, ArcFaceHead, DataLoader[tuple[Tensor, int]]]:
    """Модель-тождество, голова с единичным весом и загрузчик на три кадра.

    Батч меньше выборки (2 против 3) намеренно: порядок целей проверяется через границу
    батчей, а не внутри одного.
    """
    модель = CarClassifier(
        ВекторныйБэкбон(), ЧИСЛО_КЛАССОВ, mean=(0.5, 0.5, 0.5), std=(0.5, 0.5, 0.5)
    )
    # Блок эмбеддинга (BN → Linear → BN) заменён тождеством: его случайный вес перемешал бы
    # компоненты, по которым выписано `ОЖИДАЕМОЕ_РАНЖИРОВАНИЕ`.
    модель.embedding = nn.Identity()
    голова = ArcFaceHead(ЧИСЛО_КЛАССОВ, ЧИСЛО_КЛАССОВ, s=32.0, m=0.5)
    with torch.no_grad():
        голова.weight.copy_(torch.eye(ЧИСЛО_КЛАССОВ))
    загрузчик = DataLoader(TensorDataset(ЭМБЕДДИНГИ, МЕТКИ), batch_size=2)
    return модель, голова, загрузчик


def test_ранжирование_отдаёт_k_кандидатов_и_цели() -> None:
    модель, голова, загрузчик = подставной_замер()

    ранжирование, цели = ranked_predictions(модель, голова, загрузчик, device=УСТРОЙСТВО, k=K)

    assert [len(строка) for строка in ранжирование] == [K] * len(ОЖИДАЕМОЕ_РАНЖИРОВАНИЕ)
    assert цели == МЕТКИ.tolist()


def test_ранжирование_сортирует_по_убыванию_логитов() -> None:
    """Порядок внутри строки — по убыванию логита, а не по индексу класса.

    У кадра 0 argmax равен 1, а не 0: на нулевом argmax тест прошёл бы и у кода, который
    отдаёт индексы в их исходном порядке.
    """
    модель, голова, загрузчик = подставной_замер()

    ранжирование, _ = ranked_predictions(модель, голова, загрузчик, device=УСТРОЙСТВО, k=K)

    for кадр, (строка, ожидаемое) in enumerate(
        zip(ранжирование, ОЖИДАЕМОЕ_РАНЖИРОВАНИЕ, strict=True)
    ):
        assert строка == ожидаемое[:K], f"кадр {кадр}"


def test_узкая_голова_роняет_замер_с_упоминанием_k() -> None:
    """Узость названа в терминах запрошенного `k`, а не зашитого `TOP_K`.

    Иначе голова на двух выходах при `k=3` жаловалась бы на «меньше 5», и читатель искал бы
    несуществующее требование пяти классов. Числа в шаблоне — литералы: текст сверяется
    побайтово, подстановка `K` пропустила бы и сообщение с чужим `k`.
    """
    модель, _, загрузчик = подставной_замер()
    узкая_голова = ArcFaceHead(ЧИСЛО_КЛАССОВ, 2, s=32.0, m=0.5)

    with pytest.raises(ValueError, match=r"классов меньше 3 \(2\), top-3 не определён"):
        ranked_predictions(модель, узкая_голова, загрузчик, device=УСТРОЙСТВО, k=K)


def test_режимы_восстанавливаются_после_ранжирования() -> None:
    """Режимы модели и головы восстанавливаются по отдельности, как в `evaluate`."""
    модель, голова, загрузчик = подставной_замер()
    модель.train()
    голова.eval()

    ranked_predictions(модель, голова, загрузчик, device=УСТРОЙСТВО, k=K)

    assert модель.training is True
    assert голова.training is False


def test_evaluate_считает_как_раньше() -> None:
    """Страховка от регресса M-1.2: вынос цикла не сдвинул числа `evaluate`.

    Ожидание считается по `ОЖИДАЕМОЕ_РАНЖИРОВАНИЕ`, то есть мимо кода замера.
    """
    модель, голова, загрузчик = подставной_замер()

    метрики = evaluate(
        модель,
        голова,
        загрузчик,
        idx_to_class_id=ИНДЕКС_КЛАССОВ,
        idx_to_brand=МАРКИ_КЛАССОВ,
        device=УСТРОЙСТВО,
    )

    метки = МЕТКИ.tolist()
    ранги = list(zip(ОЖИДАЕМОЕ_РАНЖИРОВАНИЕ, метки, strict=True))
    ожидаемый_top1 = sum(ранг[0] == метка for ранг, метка in ранги) / len(метки)
    ожидаемый_top5 = sum(метка in ранг[:TOP_K] for ранг, метка in ранги) / len(метки)
    # Числа названы и явно: вырожденная фикстура (скажем, top-5 = 1.0 по построению) так не
    # пройдёт, а сверка `evaluate` с таким ожиданием ничего не утверждала бы.
    assert ожидаемый_top1 == pytest.approx(1 / 3)
    assert ожидаемый_top5 == pytest.approx(2 / 3)
    assert метрики.top1_model == pytest.approx(ожидаемый_top1)
    assert метрики.top5_model == pytest.approx(ожидаемый_top5)
