"""Иглы моделей: совпадает ли имя файла с классом каталога и откуда иглы берутся.

Внешнее свидетельство о принадлежности кадра классу на Commons одно — имя файла,
написанное человеком. CLIP этого не заменяет и заменить не может: §11 дизайна харвеста
отводит ему отсев мусора и прямо запрещает делать его гейтом принадлежности, а Land
Cruiser в классе `lexus__lx` для текстового энкодера — законная машина.

Правило совпадения отвечает на вопрос об одном имени и одном классе и ничего не знает ни
про манифест, ни про отчёты: его зовёт шлюз на приёме, где нет ни того, ни другого.

Вторая ответственность модуля — прочитать таблицу игл `catalog/model_aliases.yaml` и
провалидировать её целиком. Валидация живёт здесь же, рядом с правилом совпадения: таблицу
на 150 классов ведут руками, а опечатка в ней меняет фильтр принадлежности классу молча —
игла из одной буквы совпадёт почти с любым именем файла, и шлюз начнёт принимать в класс
чужие кадры.
"""

from __future__ import annotations

import re
import urllib.parse
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import yaml

from pipeline.normalize import strip_diacritics

_РАСШИРЕНИЕ = re.compile(r"\.(jpe?g|png|tiff?|webp|gif)$", re.IGNORECASE)
_НЕ_БУКВА_И_НЕ_ЦИФРА = re.compile(r"[^0-9a-zа-я]+")


def normalize_filename(raw: str) -> str:
    """Имя файла Commons к сравнимому виду: токены в нижнем регистре через один пробел.

    Принимает и `title` выдачи (`File:X.jpg`), и `page_url` манифеста
    (`.../wiki/File:X.jpg` с процент-кодированием): колонки `title` в манифесте нет, а
    имя нужно обоим контурам — приёму и триажу.

    Диакритика сворачивается общим с загрузчиком `catalog/aliases.yaml` хелпером
    `strip_diacritics` — буквально той же функцией, а не похожей: класс «всё, кроме букв и
    цифр, → пробел» (§6) не знает `é` и `š`, и без сворачивания `Mégane` распалось бы на
    `m gane`, где никакая игла уже не совпадёт. `catalog/harvest_queries.yaml` тянет оба
    написания (`Citroen C4` и `Citroën C4`), и сходиться они обязаны в одну строку.
    Побочный эффект NFKD принят: `й` тоже сводится к `и` — иглы проходят через эту же
    функцию, поэтому обе стороны сравнения искажаются одинаково.

    Кириллица сохраняется: на Commons есть `ВАЗ-2114`, и таблица игл имеет право на
    кириллическую иглу.
    """
    текст = urllib.parse.unquote(raw)
    текст = текст.rsplit("/wiki/", 1)[-1]
    текст = текст.removeprefix("File:")
    текст = _РАСШИРЕНИЕ.sub("", текст)
    текст = strip_diacritics(текст).lower()
    return " ".join(_НЕ_БУКВА_И_НЕ_ЦИФРА.sub(" ", текст).split())


def matches_needle(name: str, needle: str) -> bool:
    """Совпадает ли игла с нормализованным именем.

    Совпадение только по подряд идущим токенам — подстрочное дало бы «lx» внутри
    «deluxe». Одно послабление: последний токен иглы может быть продолжен цифрами, если
    кончается буквой, иначе «fx» не находит «fx35» и класс теряет живые кадры. Условие
    про букву не украшение: без него цифровая игла «2114» нашлась бы в «21145».
    """
    имя = name.split()
    игла = needle.split()
    if not игла:
        return False
    последний = игла[-1]
    хвост_разрешён = последний[-1:].isalpha()
    for начало in range(len(имя) - len(игла) + 1):
        окно = имя[начало : начало + len(игла)]
        if окно[:-1] != игла[:-1]:
            continue
        if окно[-1] == последний:
            return True
        if хвост_разрешён and окно[-1].startswith(последний):
            остаток = окно[-1][len(последний) :]
            if остаток.isdigit():
                return True
    return False


_КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
DEFAULT_ALIASES_PATH = _КОРЕНЬ / "catalog" / "model_aliases.yaml"
SUPPORTED_VERSION = 1

AliasTable = Mapping[str, tuple[str, ...]]


class AliasesError(ValueError):
    """Таблица игл не проходит валидацию."""


def load_alias_table(path: Path) -> dict[str, tuple[str, ...]]:
    """Прочитать таблицу игл и провалидировать её целиком.

    Иглы нормализуются тем же нормализатором, что и имя файла: сравнивать «Mark II» с
    «mark ii» иначе пришлось бы в каждом вызове, и рано или поздно кто-нибудь забудет.

    Любой негодный вход выходит наружу как `AliasesError`, включая нечитаемый YAML: зовёт
    загрузчик шлюз на приёме, а в задаче 5 ещё и журнал отказов, и ловят они объявленный
    контрактом тип. Трейсбек из потрохов PyYAML оборвал бы прогон вместо внятного отказа
    по таблице.
    """
    try:
        сырое: object = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as ошибка:
        raise AliasesError(f"{path}: YAML не читается: {ошибка}") from ошибка
    if not isinstance(сырое, dict):
        raise AliasesError(f"{path}: корень должен быть отображением")
    if сырое.get("version") != SUPPORTED_VERSION:
        raise AliasesError(f"{path}: поддерживается только version: {SUPPORTED_VERSION}")
    таблица = сырое.get("classes")
    if not isinstance(таблица, dict):
        raise AliasesError(f"{path}: classes должно быть отображением")

    итог: dict[str, tuple[str, ...]] = {}
    for class_id, тело in таблица.items():
        if not isinstance(тело, dict):
            raise AliasesError(f"{path}: {class_id} должен быть отображением")
        итог[str(class_id)] = _иглы_класса(path, str(class_id), тело.get("needles"))
    return итог


def _иглы_класса(path: Path, class_id: str, сырые_иглы: object) -> tuple[str, ...]:
    """Проверить и нормализовать иглы одного класса.

    Список проверяется целиком и поэлементно, потому что таблицу правят руками: скаляр
    вместо списка (`needles: "Mark II"` без дефиса) — законный YAML, но итерация пошла бы
    по строке и дала иглы из одной буквы. По той же причине от элемента требуется строка,
    а не `str(элемент)`: он превратил бы `null` в живую иглу `none`.

    Игла, от которой после нормализации ничего не осталось (`"---"`), отбрасывается молча:
    отказ здесь дал бы ложную тревогу на пунктуации внутри годной иглы. Пустым итогом
    класс всё равно не останется — на это и есть проверка ниже.

    Игла, совпавшая после нормализации с уже собранной, отбрасывается тоже — и здесь, на
    входе, а не фильтром в отчётах: две записи, отличающиеся только регистром или
    диакритикой (`Citroen C4` и `Citroën C4` в `catalog/harvest_queries.yaml`), — законная
    ручная правка, а тройки `needle_conflicts` и `broad_needles` от них двоятся. Порядок
    первых появлений сохраняется: иглы идут человеку в отчёт.
    """
    перечень = [] if сырые_иглы is None else сырые_иглы
    if not isinstance(перечень, list):
        raise AliasesError(f"{path}: needles у {class_id} должно быть списком строк")

    иглы: list[str] = []
    for игла in перечень:
        if not isinstance(игла, str):
            raise AliasesError(f"{path}: игла {игла!r} у {class_id} не строка")
        нормальная = normalize_filename(игла)
        if нормальная and нормальная not in иглы:
            иглы.append(нормальная)
    if not иглы:
        raise AliasesError(f"{path}: у {class_id} нет ни одной годной иглы")
    return tuple(иглы)


@dataclass(frozen=True, slots=True)
class AliasVerdict:
    """Что имя файла говорит о принадлежности кадра классу."""

    kind: Literal["own", "foreign", "unknown"]
    foreign: tuple[str, ...] = ()


def alias_verdict(name: str, class_id: str, table: AliasTable) -> AliasVerdict:
    """Три состояния, а не `bool`.

    Разница между «имя молчит» и «имя называет соседний класс каталога» — это разница
    между работой человека и работой программы: во втором случае свидетельство
    однозначно, и человеку нечего добавить к слову `cressida` в имени файла.

    Своя игла старше чужой: имя, называющее оба класса, остаётся своим — соседнее имя
    рядом со своим не свидетельство, а контекст («lx570 против land cruiser»).

    `name` ожидается уже пропущенным через `normalize_filename`: сама функция не нормализует
    ничего. На сыром `File:2019_Lexus_LX570.jpg` не будет ошибки — будет `unknown`, а
    `unknown` на приёме бракуется так же жёстко, как `foreign`, то есть забытая нормализация
    даёт не сбой, а массовый отказ живых кадров.

    Класс вне таблицы роняет `KeyError`, а не считается `unknown`: молчаливый пропуск
    означал бы фильтр, посчитанный не по тому классу.
    """
    if any(matches_needle(name, игла) for игла in table[class_id]):
        return AliasVerdict("own")
    чужие = tuple(
        сосед
        for сосед, иглы in sorted(table.items())
        if сосед != class_id and any(matches_needle(name, игла) for игла in иглы)
    )
    return AliasVerdict("foreign", чужие) if чужие else AliasVerdict("unknown")


def needle_conflicts(table: AliasTable) -> list[tuple[str, str, str]]:
    """Взаимно неразличимые иглы двух классов. Пустой список — таблица годна (`G_AL1`).

    Блокирует только симметрия: если игла одного класса ловит иглу другого И наоборот,
    классы неразличимы по имени, и вердикт `foreign` теряет смысл в обе стороны.

    Асимметрия сюда не попадает намеренно, и это не поблажка. ASX в США зовут «Outlander
    Sport», а Outlander — отдельный класс каталога: игла «outlander» ловит «outlander
    sport», но не наоборот. Запрет асимметрии заставил бы выкинуть более конкретную иглу
    и потерять живые кадры ASX, тогда как при живой игле своя всё равно старше чужой
    (`alias_verdict`), и вердикт получается верным без всякого запрета. Асимметричные
    пары попадают в `broad_needles` — на глаз человеку, не в блокировку.
    """
    конфликты: list[tuple[str, str, str]] = []
    имена = sorted(table)
    for i, первый in enumerate(имена):
        for второй in имена[i + 1 :]:
            for игла in table[первый]:
                if any(
                    matches_needle(игла, чужая) and matches_needle(чужая, игла)
                    for чужая in table[второй]
                ):
                    конфликты.append((первый, второй, игла))
    return конфликты


def broad_needles(table: AliasTable) -> list[tuple[str, str, str]]:
    """Иглы, накрывающие более конкретную иглу соседа. Не блокируют, но требуют взгляда.

    Голая «niva» у Chevrolet накрывает «niva 2131» у Lada. Само по себе это законно —
    своя игла старше чужой, — но опасно в паре с неполнотой: если у `lada__niva_2131`
    иглы не покрывают файл «lada niva 32545538318», сработает чужая «niva», и живой
    кадр уйдёт в автоматический дроп. Ровно так выглядели 23 строки этого класса в
    прогоне `b51eb38`. Список идёт в отчёт, чтобы человек проверил полноту своей
    стороны, а не чтобы запретить широкую иглу.
    """
    широкие: list[tuple[str, str, str]] = []
    for класс, иглы in sorted(table.items()):
        for игла in иглы:
            for сосед, чужие in sorted(table.items()):
                if сосед == класс:
                    continue
                накрывает = any(
                    чужая != игла
                    and matches_needle(чужая, игла)
                    and not matches_needle(игла, чужая)
                    for чужая in чужие
                )
                if накрывает:
                    широкие.append((класс, игла, сосед))
    return широкие
