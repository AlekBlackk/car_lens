# pipeline/harvest/gate.py
"""Пороги прогона H1–H4 и отчёт (§14 дизайна).

Пороги назначены до запуска: критерий, выбранный после того, как увидены числа, — это
подгонка критерия под результат, а не решение.

Блокирующих порогов два, и разделение — суть гейта. H3 и H4 говорят «конвейер нельзя
пускать в данные»: первый это правило 1 Р-11 и 152-ФЗ, второй — выборка без
юридического следа. Охват аудита и разбор вердиктов — `pipeline/harvest/audit.py`;
числа приходят из CSV, а не хардкодятся.

H3 блокирует по трём разным поводам, и ни один из них не «аудит что-то нашёл». Найденный и
удалённый грязный кадр — выполненная работа (§12.1 дизайна рекалибровки), и блокировка на
нём требовала бы стереть историю ради зелёного вердикта. Блокирует незакрытый **остаток**:
грязная строка, всё ещё лежащая в манифесте; **незакрытый охват**; **неразобранный спор**.
Второй повод существует потому, что «0 грязных» одинаково верно и когда аудит прошёл чисто, и
когда его не было вовсе — на этой неоднозначности прогон 2026-08-29 отрапортовал H3
«ПРОЙДЕН» на двух проверенных кадрах из двадцати восьми. Три повода названы тремя отдельными
сообщениями, потому что закрываются разной работой: правкой редакции, проходом галереи и
решением по конкретному спору.

H1 и H2 не блокируют: их провал это **измеренный дефицит**, который открывает Flickr,
Openverse и синтетический слой, а не переделку харвестера. Требовать от H1 прохождения
значило бы требовать от кода того, что зависит от содержимого чужого хранилища.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass

from pipeline.harvest.audit import AuditSummary
from pipeline.harvest.manifest import HarvestRow, ManifestError, validate
from pipeline.harvest.run import ClassOutcome

H1_MIN_CLASSES = 100
CLASS_TARGET = 30
H2_CORE_CLASSES = ("lada__2107", "lada__granta", "lada__niva_2121", "uaz__patriot")


@dataclass(frozen=True, slots=True)
class GateResult:
    """Вердикт прогона: что блокирует и что просто измерено."""

    passed: bool
    blocking_failures: tuple[str, ...]
    advisory_failures: tuple[str, ...]


def check_gate(
    outcomes: Sequence[ClassOutcome] | None,
    rows: Sequence[HarvestRow],
    audit: AuditSummary,
    allow_sa: bool,
    class_target: int = CLASS_TARGET,
) -> GateResult:
    """Проверить четыре порога и разделить провалы на блокирующие и измерительные.

    `outcomes is None` — это сборка из манифеста, а не прогон: чисел прогона нет, поэтому H1 и
    H2 не проверяются. H3 и H4 при этом работают полностью — сводка аудита и строки манифеста
    у сборки настоящие.

    Сводку гейт получает готовой, а не считает сам: половина её вопросов («ушла ли строка из
    манифеста», «что нашли на прошлых прогонах») отвечается только у границы применения
    вердиктов — по манифесту до, манифесту после и журналу применённых, а гейту достаётся
    один снимок.
    """
    блокирующие: list[str] = []
    измерительные: list[str] = []

    if outcomes is None:
        # Молчание про пропуск читалось бы как «дефицита нет». Подставить сюда счёт по
        # манифесту нельзя: манифест накопителен, и порог по нему брали 134 класса там, где
        # прогон не добрал ни одного.
        измерительные.append(
            "H1 и H2 не проверены: сборка из манифеста не знает, что набрал прогон"
        )
    else:
        добрали = sum(1 for итог in outcomes if итог.accepted >= class_target)
        if добрали < H1_MIN_CLASSES:
            измерительные.append(
                f"H1: классов с {class_target} принятыми — {добрали} < {H1_MIN_CLASSES}"
            )

        по_классам = {итог.class_id: итог.accepted for итог in outcomes}
        for class_id in H2_CORE_CLASSES:
            принято = по_классам.get(class_id, 0)
            if принято < class_target:
                измерительные.append(f"H2: ядровой {class_id} — {принято} < {class_target}")

    # Найденное и применённое не проверяется вовсе: удалённый по вердикту кадр — закрытая
    # работа (§12.1), и блокировка на нём означала бы требование стереть историю.
    if audit.dirty_remaining:
        блокирующие.append(
            f"H3: {len(audit.dirty_remaining)} кадров с читаемым номером или различимым лицом "
            f"остались в манифесте (например {audit.dirty_remaining[0]}) — правится редакция, "
            "а не список файлов"
        )

    if audit.gap:
        блокирующие.append(
            f"H3: аудит не закрыт — {len(audit.gap)} обязательных кадров без решённого "
            f"вердикта (например {audit.gap[0]}); «0 грязных» на непроверенной выборке "
            "ничего не значит"
        )

    # Спор и непросмотренный кадр закрываются разной работой — там нужен проход галереи,
    # здесь решение по конкретному кадру, — поэтому спорные названы отдельным поводом. Слить
    # их в один значило бы повторить в мелком масштабе ту самую подмену, из-за которой
    # `conflict` вообще попал когда-то в закрытый охват.
    if audit.conflicts:
        блокирующие.append(
            f"H3: {len(audit.conflicts)} спорных решений `conflict` не разобраны "
            f"(например {audit.conflicts[0]}) — спор закрывает человек, а не прогон"
        )

    try:
        validate(rows, allow_sa=allow_sa)
    except ManifestError as ошибка:
        блокирующие.append(f"H4: манифест не проходит валидацию — {ошибка}")

    return GateResult(not блокирующие, tuple(блокирующие), tuple(измерительные))


def render_report(
    outcomes: Sequence[ClassOutcome],
    rows: Sequence[HarvestRow],
    gate: GateResult,
    git_sha: str,
    ran_at: str,
    audit: AuditSummary,
    class_target: int = CLASS_TARGET,
) -> str:
    """Собрать `bench/harvest-m0.md`: числа прогона в отслеживаемом git месте.

    Разбор причин отказа печатается потому, что отказ необратим: метка кандидата уходит
    в `state.done_items` и обратно не возвращается. У `alias_mismatch` есть собственный
    журнал (`alias_rejects.csv`), у остальных причин — `over_redacted`, `not_a_car_photo`,
    `redaction_failed` — нет ничего, и без этих чисел массовый отказ по новой причине
    выглядел бы как «в Commons просто нет фотографий».

    Отчёт говорит о себе, что его причины отказа — дельта прогона: тот же прогон в
    `bench/harvest-c1.md` показан пожизненной суммой `reject_log.csv`, и без этой фразы
    расхождение двух git-отслеживаемых отчётов на одном `git_sha` читалось бы как ошибка
    одного из них.

    По той же причине сказано, что все числа — снимок прогона: применение вердиктов аудита
    удаляет строки из манифеста уже после того, как отчёт записан, и «принято фотографий»
    здесь законно расходится с числом строк в манифесте сегодня. Этот файл пишет **только**
    настоящий прогон — сборка из манифеста печатает свои числа в stdout (`scripts/harvest.py`,
    ветка `--report-only`), потому что перезапись затирала бы запись прогона.

    Найдено/применено печатается, хотя ничего не блокирует: §12.1 требует от отчёта замкнутой
    арифметики, иначе единственным следом исчезнувших из манифеста строк остаётся их
    отсутствие, а оно читается как «дефектов не было». Прогон, не нашедший ничего, и прогон,
    нашедший восемь утечек и вычистивший их, обязаны выглядеть по-разному.
    """
    отказы: Counter[str] = Counter()
    for итог in outcomes:
        отказы.update(итог.rejects)
    дефицитные = sorted(
        (итог for итог in outcomes if итог.accepted < class_target),
        key=lambda итог: итог.accepted,
    )
    вердикт_гейта = "пройден" if gate.passed else "НЕ ПРОЙДЕН"
    строки = [
        "# Харвест открытого провенанса, M0 — прогон",
        "",
        f"Прогон от {ran_at}, `git_sha` — `{git_sha}`.",
        "",
        "Числа ниже — снимок прогона. Манифест мог уехать позже: применение вердиктов аудита"
        " удаляет из него строки, и тогда «принято фотографий» здесь больше, чем строк в"
        " манифесте сейчас. Живые числа манифеста считает `bench/harvest-c1.md`.",
        "",
        f"- классов в прогоне: {len(outcomes)}",
        f"- принято фотографий: {len(rows)}",
        f"- классов, добравших {class_target}: "
        f"{sum(1 for итог in outcomes if итог.accepted >= class_target)}",
        f"- аудит H3: закрыто вердиктом {audit.resolved_total}",
        f"- дефекты приватности: найдено {len(audit.dirty_found)}, "
        f"применено {len(audit.dirty_applied)}, осталось {len(audit.dirty_remaining)}",
        f"- вердикт гейта: {вердикт_гейта}",
        "",
        "Ненулевые «найдено» и «применено» — выполненная работа аудита, а не регресс редакции:"
        " эти строки вердиктом `drop:plate`/`drop:face` уже удалены из манифеста. Блокируют"
        " только «осталось», незакрытый охват и неразобранные споры; обнулять счётчик ради"
        " зелёного вердикта запрещено (§12.1 дизайна рекалибровки).",
        "",
        "## Блокирующие провалы",
        "",
        *([f"- {причина}" for причина in gate.blocking_failures] or ["Нет."]),
        "",
        "## Измеренный дефицит (не блокирует)",
        "",
        *([f"- {причина}" for причина in gate.advisory_failures] or ["Нет."]),
        "",
        "## Причины отказа",
        "",
        "Числа — дельта этого прогона (`ClassOutcome`), а не пожизненный итог. Те же причины в"
        " `bench/harvest-c1.md` посчитаны по накопленному `reject_log.csv`, поэтому два отчёта"
        " одного прогона и одного `git_sha` расходятся законно: у них разные знаменатели.",
        "",
        "| Причина | Кандидатов |",
        "|---|---|",
        *[f"| `{причина}` | {число} |" for причина, число in отказы.most_common()],
        "",
        "## Дефицитные классы",
        "",
        "Уходят в синтетический слой Р-11. Это исход, а не ошибка прогона.",
        "",
        "| Класс | Принято | Просмотрено |",
        "|---|---|---|",
        *[f"| `{и.class_id}` | {и.accepted} | {и.seen} |" for и in дефицитные],
    ]
    return "\n".join(строки) + "\n"
