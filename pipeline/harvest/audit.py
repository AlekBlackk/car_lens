"""Протокол ручного аудита H3 и заведение его чисел в гейт.

Прогон 2026-08-29 провалил H3 вакуумно: гейт получил `audited_dirty=0`, потому что
аудит покрыл 2 кадра из 28 с номерами, а не потому что выборка чиста. Здесь охват задан
явно и проверяем: все кадры с найденными номерами/лицами, все кадры ядровых классов,
плюс случайные 200 из тех, где детектор не нашёл ничего, — контроль ложноотрицательных
пропусков.

`drop:plate` и `drop:face` — нарушение приватности: такие кадры удаляются из манифеста
**и** засчитываются в `audited_dirty`, потому что хотя бы один такой кадр означает, что
автоматика протекает системно (гейт блокирует — правится редакция, а не список файлов).
`drop:<прочее>` (не та модель, мусор) приватности не касается: кадр удаляется, в dirty
не идёт.

Вердикты приходят из двух каналов, и они не равны. Человек смотрел на пиксели, автомат
(дедуп, §8 дизайна C1) сравнивал метаданные, поэтому **автомат не перебивает человека**:
автоматический `drop:*` строке с `audit == "ok"` не удаляет её, а понижается до `conflict`
(`demote_over_human`). Применённые автовердикты уезжают в git-отслеживаемый журнал
`provenance/dedup_verdicts.csv`: строка, выброшенная из манифеста, иначе исчезает из
провенанса, а причина остаётся в файле рядом с данными, который git не видит.
"""

from __future__ import annotations

import csv
import random
from collections.abc import Mapping, Sequence
from dataclasses import asdict, dataclass, fields, replace
from pathlib import Path

from pipeline.harvest.manifest import HarvestRow

AUDIT_DIRTY = frozenset({"drop:plate", "drop:face"})
CORE_CLASSES = ("lada__2107", "lada__granta", "lada__niva_2121", "uaz__patriot")
RANDOM_CLEAN_SAMPLE = 200
#: Отметка человека, которую автомат не имеет права перебить (§8 дизайна C1).
HUMAN_OK = "ok"
#: Куда сводится след применённых автовердиктов. Рядом с манифестом, а не в каталоге
#: данных: и то и другое — юридический след выборки, обязанный пережить чистку данных.
DEFAULT_APPLIED_PATH = (
    Path(__file__).resolve().parent.parent.parent / "provenance" / "dedup_verdicts.csv"
)


@dataclass(frozen=True, slots=True)
class AppliedVerdict:
    """Автовердикт, применённый к манифесту: по какой строке и когда.

    `class_id` и `basis` дублируют колонки манифеста намеренно: строку с `drop:*` из
    манифеста удаляют, и без копии по журналу нельзя узнать даже, какой класс потерял кадр.
    """

    file: str
    class_id: str
    basis: str
    verdict: str
    applied: str
    # Колонка добавлена последней, с умолчанием (по образцу `ExpandRow.truncated`,
    # задача 12/M6): в git уже лежит журнал с двумя строками старой схемы, и читатель
    # обязан их терпеть. `verdict` — что применили к манифесту после понижения дедупа
    # по человеку (`demote_over_human`), `requested` — чего хотел дедуп до понижения.
    # Пустой `requested` означает строку, записанную до этой задачи, а не «дедуп ничего
    # не хотел»: без разделения полей понижение `ok` → `conflict` стирало бы из следа
    # сам факт вытеснения, и счёт `supersede` §9 недосчитывал бы понижённые случаи.
    requested: str = ""


APPLIED_COLUMNS = tuple(поле.name for поле in fields(AppliedVerdict))


class AuditError(ValueError):
    """CSV вердиктов не годится."""


def _годен(вердикт: str) -> bool:
    return вердикт in {"ok", "conflict"} or вердикт.startswith("drop:")


def load_audit_events(path: Path) -> list[tuple[str, str]]:
    """Прочитать CSV `file,verdict` построчно: одна запись — одно событие.

    Отдельный читатель от `load_audit` потому, что у файла две законные роли. Как очередь к
    применению он важен итогом по файлу: поздняя строка обязана вытеснить раннюю, иначе
    пересмотр решения потонул бы в прежнем. Как след прогона он важен числом строк: §9
    просит `supersede` и `conflict` поштучно, а словарь этого не даёт — два вытеснения
    одного файла схлопнулись бы в одно.
    """
    события: list[tuple[str, str]] = []
    for строка in csv.DictReader(path.read_text(encoding="utf-8").splitlines()):
        файл = (строка.get("file") or "").strip()
        вердикт = (строка.get("verdict") or "").strip()
        if not файл:
            continue
        if not _годен(вердикт):
            raise AuditError(f"{path}: непонятный вердикт {вердикт!r} у {файл}")
        события.append((файл, вердикт))
    return события


def load_audit(path: Path) -> dict[str, str]:
    """Прочитать CSV `file,verdict`: итоговый вердикт по файлу, поздняя строка побеждает."""
    return dict(load_audit_events(path))


def merge_verdicts(*verdicts: Mapping[str, str]) -> dict[str, str]:
    """Склеить вердикты нескольких проходов; поздний проход побеждает ранний.

    Порядок именно такой: второй проход смотрит кадр повторно только тогда, когда
    человек решил пересмотреть своё решение, и новый вердикт обязан вытеснить старый,
    а не потонуть в нём.
    """
    итог: dict[str, str] = {}
    for пачка in verdicts:
        итог.update(пачка)
    return итог


def apply_audit(rows: Sequence[HarvestRow], verdicts: Mapping[str, str]) -> list[HarvestRow]:
    """Проставить колонку `audit` и выкинуть строки с любым `drop:*`."""
    итог: list[HarvestRow] = []
    for строка in rows:
        вердикт = verdicts.get(строка.file, строка.audit)
        if вердикт.startswith("drop:"):
            continue
        итог.append(replace(строка, audit=вердикт))
    return итог


def demote_over_human(verdicts: Mapping[str, str], rows: Sequence[HarvestRow]) -> dict[str, str]:
    """Понизить автоматический `drop:*` до `conflict` там, где строку уже проверил человек.

    Автомат не перебивает человека. Дедуп решает спор двух классов по расстоянию хешей и
    по базису заявления, человек — по самим пикселям, поэтому заявление, подкреплённое
    отметкой `ok` в манифесте, сильнее заявления, подкреплённого категорией Commons. Первое
    же живое вытеснение это и доказало: строка `mitsubishi__pajero` с `audit=ok` была снесена
    по расстоянию ровно 6 (сам порог) против кадра `mazda__cx5` — двух разных машин одного
    фотографа в одинаковой постановке. Понижение оставляет спор в манифесте отметкой
    `conflict`, то есть отдаёт его человеку, ровно как §8 обещает для равно подкреплённых
    заявлений.

    Понижается только **автоматический** канал. Вердикты `--audit` — это и есть человек, и
    его `drop:plate` обязан сработать поверх любого прежнего `ok`: кадр с читаемым номером
    остаётся нарушением приватности, кто бы его раньше ни одобрил.
    """
    проверено = {строка.file for строка in rows if строка.audit == HUMAN_OK}
    return {
        файл: "conflict" if вердикт.startswith("drop:") and файл in проверено else вердикт
        for файл, вердикт in verdicts.items()
    }


def suppress_applied(
    verdicts: Mapping[str, str], applied: Sequence[AppliedVerdict]
) -> dict[str, str]:
    """Убрать из `verdicts` то, что журнал уже помнит запрошенным.

    `verdicts` обязан быть вердиктом ДО понижения по человеку (сырой очередью дедупа,
    `load_audit` очереди, а не результатом `demote_over_human`) — вызывать до понижения, не
    после. Понижение зависит от текущей отметки в манифесте, а она может смениться уже
    после того, как этот самый запрос был применён и залогирован (кадр получил `audit=ok`
    позже), поэтому у одного и того же запроса понижение способно дать разный результат от
    прогона к прогону. Сверка по понижённому вердикту искала бы то, что понижение даёт
    сегодня, а не то, что журнал помнит с прошлого раза, и не находила бы совпадения там,
    где оно есть — ровно так подавление один раз промолчало на живых данных C1b.

    Сверка идёт по паре «файл + запрошенный вердикт», не по одному файлу: вердикт по тому же
    кадру может смениться (человек пересмотрел строку, дедуп на следующем прогоне решил
    иначе), и подавление по одному имени похоронило бы такую законную правку молча. Один и
    тот же вердикт на тот же файл подавляется и в честном сценарии: кадр, вычищенный
    прополкой и принятый заново под тем же детерминированным `{sha}.jpg`, законно получает от
    дедупа тот же вердикт повторно — это не пересмотр, а совпадение, и подавление тут
    корректно, а не только терпимо.

    Запрошенный вердикт записи журнала — это `requested`, а не `verdict`: `verdict` несёт
    уже понижённый (применённый) вердикт. Пустой `requested` (записи до этой задачи, когда
    понижения ещё не было и запись хранит `verdict` как есть) читается как «`verdict` и есть
    был запрошенным» — то же допущение, которым `append_applied` мигрирует старую шапку.

    Обычно очередь `verdicts.dedup.csv` после применения усекается (`scripts/harvest.py`),
    и до этой строки очередь пуста, а подавлять нечего. Это — вторая линия защиты на случай,
    когда очередь усечение пережила: прогон прервался между применением и усечением, очередь
    восстановили из копии, или вердикты применила версия кода без усечения (ровно случай,
    найденный финальным ревью ветки C1).
    """
    запрошено_журналом = {(запись.file, запись.requested or запись.verdict) for запись in applied}
    return {
        файл: вердикт
        for файл, вердикт in verdicts.items()
        if (файл, вердикт) not in запрошено_журналом
    }


def describe_applied(
    requested: Mapping[str, str],
    applied: Mapping[str, str],
    rows: Sequence[HarvestRow],
    applied_at: str,
) -> list[AppliedVerdict]:
    """Записи журнала по вердиктам дедупа и манифесту **до** их применения.

    Два вердикта на входе, а не один: `requested` — что хотел дедуп до понижения по человеку,
    `applied` — что фактически применилось к манифесту после него. Строка проходит по
    `applied` (это то, что применилось), но обязана нести оба — иначе понижение `ok` →
    `conflict` стёрло бы из следа сам факт вытеснения.

    `requested.get(файл, "")` — не фоллбэк на `вердикт`: в штатном пути `applied` всегда
    подмножество ключей `requested` (после `demote_over_human` и `suppress_applied`
    ключи не прибавляются), и файл без записи в `requested` в юридический след не должен
    попасть выдуманным «дедуп хотел то же, что применили» — честнее записать «неизвестно».

    Строки, которых в манифесте нет, пропускаются: вердикт на отсутствующий файл ничего не
    изменил, и записывать его в журнал применённых значило бы врать о применении.
    """
    по_файлу = {строка.file: строка for строка in rows}
    return [
        AppliedVerdict(
            file=файл,
            class_id=по_файлу[файл].class_id,
            basis=по_файлу[файл].basis,
            verdict=вердикт,
            applied=applied_at,
            requested=requested.get(файл, ""),
        )
        for файл, вердикт in applied.items()
        if файл in по_файлу
    ]


def _шапка(path: Path) -> list[str] | None:
    """Имена колонок первой строки файла, `None` если файла нет или он пуст."""
    if not path.exists() or path.stat().st_size == 0:
        return None
    with path.open(encoding="utf-8", newline="") as файл:
        return next(csv.reader(файл), None)


def _переписать_атомарно(path: Path, verdicts: Sequence[AppliedVerdict]) -> None:
    """Полная перезапись журнала новой шапкой: временный файл рядом, затем переименование.

    Атомарность обязательна — журнал юридический, обрыв процесса посередине не должен
    оставить его наполовину переписанным файлом с частью строк под старой шапкой, а
    частью под новой.
    """
    временный = path.with_suffix(path.suffix + ".tmp")
    with временный.open("w", encoding="utf-8", newline="") as файл:
        писатель = csv.DictWriter(файл, fieldnames=list(APPLIED_COLUMNS))
        писатель.writeheader()
        for запись in verdicts:
            писатель.writerow(asdict(запись))
    временный.replace(path)


def append_applied(path: Path, verdicts: Sequence[AppliedVerdict]) -> None:
    """Дописать применённые автовердикты в журнал, создав файл с шапкой при первом вызове.

    Читает журнал перед записью, чтобы не дописать пару «файл + вердикт», которая там уже
    есть. Лишнее чтение на каждый вызов — журнал юридический, а вызов один на прогон, так
    что цена неощутима, а без неё заряженная (не усечённая) очередь дублировала бы уже
    записанную строку при каждом следующем прогоне.

    Если шапка файла не совпадает с текущим набором колонок (в git лежит пятиколоночный
    `dedup_verdicts.csv`, записанный до поля `requested`), журнал переписывается целиком:
    значения существующих строк переживают перезапись байт в байт, `requested` у них
    достраивается пустым — это и есть правда, те записи сделаны до появления поля. Запрет
    трогать журнал руками (задача 14) относится к данным, не к форме шапки: то же лечение
    план предлагает для остатка 2 «перезаписью шапки при несовпадении набора колонок».
    """
    if not verdicts:
        return
    существующие = load_applied(path)
    уже_в_журнале = {(запись.file, запись.verdict) for запись in существующие}
    новые = [запись for запись in verdicts if (запись.file, запись.verdict) not in уже_в_журнале]
    if not новые:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    шапка = _шапка(path)
    if шапка is not None and шапка != list(APPLIED_COLUMNS):
        _переписать_атомарно(path, [*существующие, *новые])
        return
    # Файл нулевой длины — файл без шапки (идиома `rejects.append_reject_row`): журнал
    # укорачивают `> файл`, и без проверки размера первая дописанная строка стала бы шапкой.
    новый_файл = not path.exists() or path.stat().st_size == 0
    with path.open("a", encoding="utf-8", newline="") as файл:
        писатель = csv.DictWriter(файл, fieldnames=list(APPLIED_COLUMNS))
        if новый_файл:
            писатель.writeheader()
        for запись in новые:
            писатель.writerow(asdict(запись))


def load_applied(path: Path) -> list[AppliedVerdict]:
    """Прочитать журнал целиком; отсутствие файла — пустой журнал, а не ошибка.

    Колонка `requested` читается терпимо (`.get(...) or ""`): в git уже лежат две строки
    старой схемы без неё, записанные до этой задачи — ровно как `load_expand_rows` терпит
    отсутствие `truncated` в журналах до M6.
    """
    if not path.exists():
        return []
    return [
        AppliedVerdict(
            file=строка["file"],
            class_id=строка["class_id"],
            basis=строка["basis"],
            verdict=строка["verdict"],
            applied=строка["applied"],
            requested=строка.get("requested") or "",
        )
        for строка in csv.DictReader(path.read_text(encoding="utf-8").splitlines())
    ]


def audit_counts(rows: Sequence[HarvestRow]) -> tuple[int, int]:
    """`(audited_total, audited_dirty)` по строкам до удаления dirty."""
    total = sum(1 for с in rows if с.audit)
    dirty = sum(1 for с in rows if с.audit in AUDIT_DIRTY)
    return total, dirty


def counts_with_verdicts(
    rows: Sequence[HarvestRow], verdicts: Mapping[str, str]
) -> tuple[int, int]:
    """`audit_counts` с новыми вердиктами, наложенными поверх колонки `audit` манифеста.

    Считает безусловно, а не только когда `verdicts` непусты: отметка аудита — свойство
    манифеста, накопленное за все прошлые прогоны, а не самого текущего запуска. После
    усечения очереди (задача 14) пустой файл вердиктов — штатное состояние между
    прогонами `--audit`, а не признак того, что аудита не было; строка `drop:plate`,
    поставленная человеком когда-то раньше, обязана попасть в счёт и сегодня.

    Наложение идёт ДО `apply_audit`: тот выкидывает из манифеста все строки с `drop:*`, и
    счёт после него навсегда получал бы `audited_dirty == 0` — ровно та тишина, из-за
    которой гейт H3 не сработал бы никогда на рукописной отметке `drop:plate`.
    """
    с_вердиктами = [
        replace(строка, audit=verdicts.get(строка.file, строка.audit)) for строка in rows
    ]
    return audit_counts(с_вердиктами)


def required_audit_files(rows: Sequence[HarvestRow], seed: int = 0) -> set[str]:
    """Какие `file` обязаны быть в аудите по протоколу §14."""
    надо: set[str] = set()
    чистые: list[str] = []
    for строка in rows:
        if строка.plates > 0 or строка.faces > 0 or строка.class_id in CORE_CLASSES:
            надо.add(строка.file)
        else:
            чистые.append(строка.file)
    выборка = random.Random(seed).sample(чистые, min(RANDOM_CLEAN_SAMPLE, len(чистые)))
    надо.update(выборка)
    return надо


def audit_gap(rows: Sequence[HarvestRow], seed: int = 0) -> set[str]:
    """Обязательные по §14 кадры, у которых нет вердикта.

    Отличает «аудит прошёл и чист» от «аудита не было»: `audited_dirty == 0` верно в обоих
    случаях, и на этой неоднозначности прогон 2026-08-29 отрапортовал H3 вакуумно. Пустая
    недостача — единственное доказательство, что протокол закрыт, а не пропущен.
    """
    надо = required_audit_files(rows, seed=seed)
    проверено = {строка.file for строка in rows if строка.audit}
    return надо - проверено
