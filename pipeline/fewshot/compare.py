def read_fewshot_metrics(path: Path) -> FewShotMetrics:
    """Прочитать замер few-shot из `fewshot_metrics.json`.

    Требуются четыре поля метрики; лишние ключи файла (`gate_passed`, `gate_failures`,
    `deficient_classes`, `refined_classes`) игнорируются молча: базис носит рядом вердикт своего
    гейта, и спорить с ним чтению незачем.

    `ValueError` называет отсутствующее поле поимённо. Базис без `per_class_support` дал бы
    отчёт, где поклассовые дельты есть, а числа кадров рядом с ними нет, то есть доля читалась
    бы как измерение.
    """
    данные = json.loads(path.read_text(encoding="utf-8"))
    отсутствуют = [поле for поле in _ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ if поле not in данные]
    if отсутствуют:
        raise ValueError(f"{path}: в замере few-shot нет полей {', '.join(отсутствуют)}")

    поклассово = {str(класс): float(доля) for класс, доля in данные["per_class_top3"].items()}
    опора = {str(класс): int(кадров) for класс, кадров in данные["per_class_support"].items()}
    return FewShotMetrics(
        top1=float(данные["top1"]),
        top3=float(данные["top3"]),
        per_class_top3=поклассово,
        per_class_support=опора,
    )


def decision_rule(*, baseline_top3: float, finetune_top3: float) -> str:
    """Какое правило §5 сработало — вместе с тем, что оно предписывает.

    Правила не пересекаются и покрывают ось целиком: на границе побеждает то, у которого
    сравнение нестрогое (`≤ +0.05` — правило 1, `> +0.10` — правило 2).

    Сравнение идёт с порогами «базис плюс полоса», а не с разностью: в двоичных float
    `0.6290 + 0.05 - 0.6290` равно 0.050000000000000044, и «ровно +0.05» ушло бы в правило 3.
    Граница, названная до прогона, не имеет права съезжать на дрожании последнего бита.
    """
    прирост = finetune_top3 - baseline_top3
    if finetune_top3 <= baseline_top3 + RULE_MARGIN_LOW:
        return (
            f"Правило 1 (прирост {прирост:+.4f} ≤ +{RULE_MARGIN_LOW:.2f}): рычаг в данных, "
            "не в архитектуре. Сначала дефект B (чужие модели в классах), потом A (заливка), "
            "потом объём харвеста. Гиперпараметры не крутим."
        )
    if finetune_top3 > baseline_top3 + RULE_MARGIN_HIGH:
        return (
            f"Правило 2 (прирост {прирост:+.4f} > +{RULE_MARGIN_HIGH:.2f}): у дообучения "
            "есть запас. Приёмка §5.2 и гейт приватности при этом остаются закрытыми, то есть "
            "это разрешение продолжать, а не результат."
        )
    return (
        f"Правило 3 (прирост {прирост:+.4f} между +{RULE_MARGIN_LOW:.2f} и "
        f"+{RULE_MARGIN_HIGH:.2f}): неопределённость. Записываем и идём дальше без решения."
    )


def render_comparison(
    *,
    finetune: FewShotMetrics,
    finetune_head: FewShotMetrics,
    baseline: FewShotMetrics,
    gate: FewShotGateResult,
    provenance: RunProvenance,
) -> str:
    """Собрать `bench/finetune-ru.md`; порядок разделов — из §7 дизайна.

    `finetune` — главная трасса (через индекс), `finetune_head` — справочная (через голову
    ArcFace), `gate` посчитан по главной. Отчёт перезаписывается целиком, поэтому рукописных
    разделов в нём нет: всё, что должно в нём быть, живёт в этом модуле.
    """
    return "\n".join(
        [
            *_шапка(provenance, finetune),
            *_лицом_к_лицу(finetune, baseline, catalog_classes=provenance.catalog_classes),
            *_две_трассы(finetune, finetune_head),
            *_справочная_линия(finetune, gate, catalog_classes=provenance.catalog_classes),
            *_поклассовые_дельты(finetune, baseline),
            *_ожидание_против_факта(finetune, baseline),
            *_искажения(provenance),
        ]
    )


