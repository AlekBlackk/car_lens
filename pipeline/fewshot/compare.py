def _абзац(текст: str, *, отступ: str = "", продолжение: str = "") -> list[str]:
    """Длинный абзац, свёрнутый по ширине отчёта; у пунктов списка — висячий отступ."""
    свёрнутый = textwrap.fill(
        текст, width=_ШИРИНА, initial_indent=отступ, subsequent_indent=продолжение
    )
    return свёрнутый.splitlines()
