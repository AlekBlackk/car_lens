"""Сравнение дообучения с few-shot базисом на одной линейке (§4, §5, §7 дизайна прогона).

Вопрос прогона ровно один: даёт ли дообучение прирост над few-shot числом **на той же
линейке**. Поэтому оба числа приходят сюда уже сведёнными `aggregate_fewshot`, а модуль считает
разности и печатает отчёт: второй реализации top-3 в репозитории быть не должно.

Torch здесь нет намеренно — по той же причине, по которой его нет в `pipeline.fewshot.metrics`:
иначе сравнение нельзя было бы проверить в окружении без группы `train`. Замер живёт в
`scripts/eval_finetune_ru.py`, где torch импортируется внутри функций.

Отдельный модуль, а не параметр к `render_report` из `pipeline.fewshot.gate`: тот печатает
шапку одного замера — энкодер и sha256 индекса CLIP — под заголовком «Few-shot baseline M2»,
то есть описывает замер, а не сравнение двух замеров.

Полосы ожидания, границы правил и числа искажений лежат здесь литералами и скопированы из
`bench/finetune-ru-preregistration.md`, записанной до прогона: критерий, выбранный после того,
как увидены числа, — подгонка критерия под результат. Отчёт генерируется целиком и
перезаписывается `write_text`, поэтому дописывать в него руками нечего — правится этот модуль.

`top1_brand` в отчёт не идёт: у пяти платформенных групп русского каталога `brand is None`, и
few-shot марку не считает намеренно.
"""

