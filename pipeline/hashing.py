"""Битовые операции над перцептивными хешами.

Модуль намеренно не знает ни про изображения, ни про pandas: на входе
целые числа, на выходе целые числа. Это позволяет `split.py` проверять
инвариант 5, не втягивая в свой граф импортов OpenCV и Pillow.

`phash` хранится в parquet как int64 с той же битовой картиной, что и
uint64 (§13.1), поэтому значения приходят со знаком. Все операции
маскируют младшие 64 бита и на знак не смотрят.
"""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Iterator, Sequence

HASH_BITS = 64

_БИТ_В_КУСКЕ = 8
_КУСКОВ = HASH_BITS // _БИТ_В_КУСКЕ
_МАСКА_КУСКА = (1 << _БИТ_В_КУСКЕ) - 1
_МАСКА = (1 << HASH_BITS) - 1


def hamming(a: int, b: int) -> int:
    """Расстояние Хэмминга между младшими 64 битами двух целых."""
    return int(((a ^ b) & _МАСКА).bit_count())


def close_pairs(hashes: Sequence[int], max_distance: int) -> Iterator[tuple[int, int]]:
    """Пары индексов, чьи хеши расходятся не более чем на `max_distance` бит.

    Каждая пара выдаётся ровно один раз, индексы внутри пары возрастают.

    Метод точный, а не приближённый. Хеш режется на восемь кусков по
    восемь бит. Если два хеша расходятся не более чем в семи битах, эти
    биты задевают не более семи кусков, значит хотя бы один кусок
    совпадает дословно — и пара обязательно окажется в общей корзине.
    Сравнивать все пары подряд не нужно: на шестнадцати тысячах записей
    это 130 миллионов сравнений, то есть минуты на пустом месте.

    Порог от восьми ломает это рассуждение, поэтому отвергается явно, а
    не тихо теряет пары. Проверка порога живёт здесь, а не в генераторе
    ниже: тело генератора не выполняется до первого `next`, так что иначе
    `close_pairs(хеши, 8)` без обхода промолчал бы вместо отказа.
    """
    if max_distance >= _КУСКОВ:
        raise ValueError(f"порог {max_distance} не меньше числа кусков {_КУСКОВ}: метод неточен")
    return _пары_по_корзинам(hashes, max_distance)


def _пары_по_корзинам(hashes: Sequence[int], max_distance: int) -> Iterator[tuple[int, int]]:
    """Обход корзин без накопления выданных пар.

    Пара, совпавшая кусками, совпала ими в каком-то самом младшем куске.
    Выдаём её только из этого куска, а из остальных пропускаем — проверка
    получается локальной, и множество выданных пар не нужно вовсе.
    Хранить его нельзя: кандидатов порядка C(n, 2)/32 — восемь корзин на
    хеш, по 256 значений в каждой, — то есть примерно n²/64, и на
    шестнадцати тысячах записей это четыре миллиона кортежей и триста с
    лишним мегабайт. Корзины срезают константу в 32 раза относительно
    полного перебора, но не меняют асимптотику.
    """
    корзины: dict[tuple[int, int], list[int]] = defaultdict(list)
    for индекс, хеш in enumerate(hashes):
        for номер in range(_КУСКОВ):
            кусок = (хеш >> (номер * _БИТ_В_КУСКЕ)) & _МАСКА_КУСКА
            корзины[(номер, кусок)].append(индекс)

    for (номер, _), соседи in корзины.items():
        for позиция, первый in enumerate(соседи):
            for второй in соседи[позиция + 1 :]:
                # Куски сравниваем по маскированному XOR: кусок совпал
                # дословно ровно тогда, когда в различии он нулевой. Для
                # номеров до седьмого это то же самое, что сравнивать
                # куски исходных значений, отрицательных в том числе, —
                # у int64 бит 63 последний.
                различие = (hashes[первый] ^ hashes[второй]) & _МАСКА
                выдана_ниже = False
                for m in range(номер):
                    if (различие >> (m * _БИТ_В_КУСКЕ)) & _МАСКА_КУСКА == 0:
                        выдана_ниже = True
                        break
                if выдана_ниже:
                    continue
                # `различие.bit_count()` — это `hamming`, но XOR уже посчитан.
                if различие.bit_count() <= max_distance:
                    yield (первый, второй)
