"""Отбор отложенного эталона `holdout_ru` (правило 2 Р-11, §3.5).

Единица отбора — не фотография, а серия автора: `listing_id = "{source}:{class_id}:{author}"`.
Автор Commons заливает серию ракурсов одного экземпляра машины одним пакетом, и разнесение
такой серии между эталоном и обучением даёт ту же утечку, от которой §3.5 защищается
сплитом по объявлению. Класс входит в ключ потому, что один автор снимает машины разных
классов, а один `listing_id` в двух сплитах — нарушение инварианта 1 §13.1, даже когда
речь о разных фотографиях.

**Когда правило «автор — один экземпляр» ложно.** Часть заливщиков Commons ведёт
многолетнюю галерею: `Throwawayacc222` дал 27 кадров `lada__granta` разных годов, кузовов
и цветов одним `listing_id`, минимальное расстояние pHash внутри серии — 16 при пороге
утечки 6. Такая серия не влезает в цель, класс остаётся без эталона, и порог G_FS2 по нему
становится неизмерим. Поэтому у класса, который иначе остаётся без эталона, серия дробится
на компоненты связности по pHash. Порог дробления равен порогу инварианта 5 §13.1 и другим
быть не может: компонента — это в точности то, что нельзя разнести по сплитам, не нарушив
инвариант. Дробление включается только при недоборе: там, где консервативный ключ
бесплатен, он остаётся.

Дробление признаётся ценой, а не улучшением: оно допускает утечку автора между эталоном и
пулом. Расстояние pHash внутри дробимых серий не меньше десяти, то есть кадры визуально
различны, — но «различны» не значит «разные машины»: фронт и корма одного экземпляра тоже
далеки. Цена платится ровно за те классы, у которых иначе нет метрики вовсе.

В эталон идут только кадры с вердиктом человека `ok`. `conflict` — это «человек не
уверен», и место такому кадру в обучающем пуле, а не в мере, по которой судят модель.
Фильтр вердиктов применяется к **единице**, а не к серии автора: иначе один `conflict`
внутри серии из двадцати семи выбрасывает все двадцать семь, и `bmw__x5` терял двадцать
девять чистых кадров из тридцати.

Класс обязан оставить пулу `POOL_RESERVE` кадров. Без них у класса не будет центроидов, и
эталон мерил бы класс, которого нет в индексе, — гарантированный промах на каждом кадре
вместо измерения.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass

from pipeline.harvest.manifest import HarvestRow
from pipeline.hashing import bucket_of, close_pairs
from pipeline.split import DEFAULT_PHASH_HAMMING

HOLDOUT_TARGET = 10
HOLDOUT_MIN = 5
# Насколько единице позволено перебрать цель. Без допуска серия из шести кадров никогда
# не влезет в остаток из четырёх, и класс останется без эталона при полном наборе фото.
OVERSHOOT = 2
# Сколько кадров класс обязан оставить обучающему пулу. Равно числу центроидов класса в
# индексе (§13.2): меньше кадров означало бы, что слоты добиваются повторами. Константа
# не импортируется из `training.build_index` намеренно — отбор эталона не должен знать
# про torch-путь сборки индекса, а значение здесь важно как «сколько оставить», а не как
# «сколько центроидов».
POOL_RESERVE = 4


@dataclass(frozen=True, slots=True)
class HoldoutSelection:
    """Что ушло в эталон, каким классам его не хватило и по какому ключу шёл отбор.

    `units` — пары «файл → ключ неделимой единицы» для **всех** строк манифеста,
    отсортированные по файлу. Кортеж, а не словарь: `HoldoutSelection` остаётся
    хешируемой, а вызывающий делает `dict(...)` один раз. Ключ нужен наружу потому, что
    инвариант 1 §13.1 проверяет `listing_id` в parquet, и там обязан лежать ключ той
    единицы, которой шёл отбор, — иначе инвариант проверяет не то, что решал отбор.
    """

    files: frozenset[str]
    short_classes: tuple[str, ...]
    refined_classes: tuple[str, ...]
    units: tuple[tuple[str, str], ...]


def listing_id_of(row: HarvestRow) -> str:
    """Ключ серии автора: источник, класс и автор."""
    return f"{row.source}:{row.class_id}:{row.author}"


def classes_short_of_holdout(
    selection: HoldoutSelection,
    rows: Sequence[HarvestRow],
    class_ids: Iterable[str],
    minimum: int = HOLDOUT_MIN,
) -> tuple[str, ...]:
    """Классы каталога, у которых в эталоне меньше `minimum` кадров.

    Знаменатель — каталог, а не классы манифеста, и это не придирка к формулировке.
    `select_holdout` раскладывает по классам **строки манифеста**, поэтому класс, у
    которого строк нет вовсе, в `short_classes` не попадает ни разу: он не «набрал мало»,
    он вообще не рассматривался. Дефицит занижается ровно в самом тяжёлом случае — на BASE
    `14a70bf` это давало 15 против настоящих 16 (`chevrolet__lanos` без единой строки), а
    гейт `G_C1` мерит именно дефицит каталога: сколько классов каталога остались без
    честного эталона. Поэтому проверка идёт по каждому классу каталога, а не по тому, что
    нашлось в манифесте.

    Считается по `selection.files`, а не по `selection.short_classes`, по той же причине:
    множество коротких классов знает только о рассмотренных, а число эталонных кадров
    класса определено для любого класса каталога, в том числе для нулевого.
    """
    в_эталоне: Counter[str] = Counter(
        строка.class_id for строка in rows if строка.file in selection.files
    )
    return tuple(sorted(класс for класс in class_ids if в_эталоне[класс] < minimum))


def phash_components(rows: Sequence[HarvestRow], max_distance: int) -> dict[str, str]:
    """Метка компоненты связности по pHash для каждого файла.

    Компонента — это в точности то, что нельзя разнести по сплитам, не нарушив
    инвариант 5 §13.1: близкие хеши обязаны лежать в одном сплите.

    Объединение по корням, а не попарная разметка: пары приходят от `close_pairs` в
    произвольном порядке, и при `a≈b`, `b≈c`, `a≉c` должна получиться одна компонента из
    трёх кадров, а не две пары.

    Метка компоненты — лексикографически минимальное имя файла в ней, а не номер корня:
    номер корня — это позиция строки в манифесте, и он уехал бы при любой переderivации,
    сортировке или дописывании манифеста. Метка попадает в ключ единицы, ключ задаёт
    порядок отбора, поэтому позиционная метка означала бы, что эталон дробимых классов
    пересобирается заново на тех же данных, а G_FS2 по этим классам несравним между
    прогонами. Содержательная метка снимает это: она зависит от того, какие кадры попали
    в компоненту, а не от того, в каком порядке они пришли.

    Оговорка о границах: ключ единицы — `listing_id#<метка>`, поэтому компонента держится
    вместе только внутри серии одного автора; компонента, растянутая на двух авторов, всё
    равно разъедется по разным единицам. На настоящих данных этого не случалось, а если
    случится — поймает `_инвариант_5_нет_близких_phash` (`pipeline/split.py`): он сравнивает
    пары кадров, не глядя на автора.
    """
    родитель = list(range(len(rows)))

    def корень(индекс: int) -> int:
        while родитель[индекс] != индекс:
            родитель[индекс] = родитель[родитель[индекс]]
            индекс = родитель[индекс]
        return индекс

    for первый, второй in close_pairs([строка.phash for строка in rows], max_distance):
        левый, правый = корень(первый), корень(второй)
        if левый != правый:
            родитель[max(левый, правый)] = min(левый, правый)
    метка: dict[int, str] = {}
    for номер, строка in enumerate(rows):
        корневой = корень(номер)
        метка[корневой] = min(метка.get(корневой, строка.file), строка.file)
    return {строка.file: метка[корень(номер)] for номер, строка in enumerate(rows)}


def _набрать(
    единицы: Mapping[str, list[HarvestRow]], цель: int, предел: int, seed: int
) -> list[str]:
    """Файлы эталона из готовой раскладки по единицам.

    Единица, в которой есть хоть один вердикт кроме `ok`, не рассматривается целиком:
    неделимость работает в обе стороны, и половину единицы в эталон брать нельзя.

    Порядок задаёт `bucket_of` по ключу единицы, а не генератор случайных чисел: отбор
    обязан зависеть только от ключа и семени, но не от порядка строк в манифесте.
    """
    чистые = {
        ключ: группа
        for ключ, группа in единицы.items()
        if all(строка.audit == "ok" for строка in группа)
    }
    набрано: list[str] = []
    for ключ in sorted(чистые, key=lambda к: bucket_of(к, seed)):
        if len(набрано) >= цель:
            break
        группа = чистые[ключ]
        if len(набрано) + len(группа) > предел:
            continue
        набрано += [строка.file for строка in группа]
    return набрано


def select_holdout(
    rows: Sequence[HarvestRow],
    target: int = HOLDOUT_TARGET,
    minimum: int = HOLDOUT_MIN,
    seed: int = 1337,
    pool_reserve: int = POOL_RESERVE,
    max_distance: int = DEFAULT_PHASH_HAMMING,
) -> HoldoutSelection:
    """Выбрать эталонные кадры каждого класса, не разрывая неделимую единицу.

    Два уровня, и порядок между ними — суть решения. Сначала единицей берётся серия
    автора. Если класс так не набрал `minimum`, серия дробится на компоненты pHash и
    попытка повторяется — но только для этого класса и только если уточнение действительно
    помогло. Классы, которым грубого ключа хватило, о дроблении не узнают.

    `pool_reserve` кадров остаются пулу всегда: и `цель`, и допуск `OVERSHOOT` режутся
    запасом, иначе перебор съел бы резерв ровно на тех классах, где он критичен.
    """
    по_классам: dict[str, list[HarvestRow]] = defaultdict(list)
    for строка in rows:
        по_классам[строка.class_id].append(строка)

    выбранные: set[str] = set()
    короткие: list[str] = []
    дроблёные: list[str] = []
    ключ_единицы: dict[str, str] = {}

    for class_id in sorted(по_классам):
        свои = по_классам[class_id]
        запас = len(свои) - pool_reserve
        цель = min(target, запас)
        предел = min(цель + OVERSHOOT, запас)

        грубые: dict[str, list[HarvestRow]] = defaultdict(list)
        for строка in свои:
            грубые[listing_id_of(строка)].append(строка)
        ключи = {строка.file: listing_id_of(строка) for строка in свои}
        набрано = _набрать(грубые, цель, предел, seed) if цель >= minimum else []

        if цель >= minimum and len(набрано) < minimum:
            компонента = phash_components(свои, max_distance)
            тонкие_ключи = {
                строка.file: f"{listing_id_of(строка)}#{компонента[строка.file]}" for строка in свои
            }
            тонкие: dict[str, list[HarvestRow]] = defaultdict(list)
            for строка in свои:
                тонкие[тонкие_ключи[строка.file]].append(строка)
            уточнённое = _набрать(тонкие, цель, предел, seed)
            if len(уточнённое) >= minimum:
                дроблёные.append(class_id)
                набрано, ключи = уточнённое, тонкие_ключи

        ключ_единицы.update(ключи)
        if len(набрано) < minimum:
            короткие.append(class_id)
            continue
        выбранные.update(набрано)

    return HoldoutSelection(
        files=frozenset(выбранные),
        short_classes=tuple(короткие),
        refined_classes=tuple(дроблёные),
        units=tuple(sorted(ключ_единицы.items())),
    )
