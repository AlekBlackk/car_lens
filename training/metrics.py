"""Метрики закрытого множества: top-1/top-5 по модели и top-1 по марке.

Единица оценки — класс §13.2, а не модель: платформенная группа занимает один
выход головы, и метрика считается по нему. Отсюда `class_id` в подписях
`per_class_recall` — `grp__…` у группы и `model_id` у одиночной модели.

Марка приходит отдельной картой, из каталога, и из `class_id` не выводится.
Префикс до `__` описывал бы марку только у одиночной модели: у одномарочной
группы он `grp`, то есть верный ответ по марке считался бы промахом, а две
разные разнобрендовые группы — совпадением. Марка класса пуста ровно тогда,
когда участники разных марок, и пустая марка не совпадает ни с чем, включая
другую пустую: две разнобрендовые группы — это две группы, а не «одна марка».

Следствие, которое видно в отчёте: у класса без марки верный ответ считается
попаданием в `top1_model`, но не в `top1_brand`, поэтому на каталоге с
разнобрендовыми группами `top1_brand` может оказаться ниже `top1_model`.
Марки у такого класса нет, и приписать ей попадание значило бы придумать её.

Метрик открытого множества (AUROC, FPR@TPR95, ECE) здесь нет: без негативов
они не определены, а посчитанные «как получится» ввели бы в заблуждение.
Долг зафиксирован в §11 дизайна.

Модуль не импортирует torch (Р-14): на вход идут готовые индексы top-5.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Metrics:
    """Метрики одного прогона по сплиту."""

    top1_model: float
    top5_model: float
    top1_brand: float
    per_class_recall: dict[str, float]


def марки_совпали(предсказанная: str | None, истинная: str | None) -> bool:
    """Совпадение марок. Пустая марка не совпадает ни с чем, включая пустую.

    `None` — не «марка неизвестна», а «марок несколько»: так каталог помечает
    разнобрендовую группу §13.2. Считать два таких класса одной маркой значит
    объявить Geely и Belgee, скажем, тем же брендом, что Toyota и Peugeot.
    """
    return предсказанная is not None and предсказанная == истинная


TOP_K = 5


def aggregate(
    top5: Sequence[Sequence[int]],
    targets: Sequence[int],
    *,
    idx_to_class_id: Mapping[int, str],
    idx_to_brand: Mapping[int, str | None],
) -> Metrics:
    """Свести предсказания в метрики.

    `top5[i]` — индексы классов по убыванию уверенности, `top5[i][0]` —
    предсказание top-1; список короче пяти отвергается, иначе top-3 посчитался
    бы как top-5 под именем `top5_model`. Список длиннее пяти допустим, но
    попадание считается только по первым `TOP_K`.
    `targets[i]` — истинный индекс класса.
    `idx_to_brand` — марка класса из каталога, `None` у разнобрендовой группы.
    `KeyError`, если встретился индекс, которого нет в `idx_to_class_id`:
    разъехавшийся каталог обязан ронять оценку, а не занижать её молча.
    `ValueError`, если `idx_to_class_id` неинъективен или наборы индексов двух
    карт не совпадают — см. ниже.
    """
    if len(top5) != len(targets):
        raise ValueError(f"несовпадение длин: {len(top5)} предсказаний, {len(targets)} меток")
    if not targets:
        raise ValueError("пустая выборка")
    # Две карты вместо одной могут разъехаться, и молчаливый исход тут хуже
    # любого: недостающий индекс уронил бы оценку `KeyError` из середины цикла
    # — и только если этому классу довелось встретиться в выборке.
    if set(idx_to_brand) != set(idx_to_class_id):
        лишние = sorted(set(idx_to_brand) - set(idx_to_class_id))
        нехватка = sorted(set(idx_to_class_id) - set(idx_to_brand))
        raise ValueError(
            f"idx_to_brand не совпадает с idx_to_class_id по индексам: "
            f"нет марки у {нехватка}, лишних марок {лишние}"
        )
    # Два индекса с одним `class_id` перетёрли бы друг друга в `per_class_recall`:
    # число классов в отчёте молча уменьшилось бы, а recall склеился по двум
    # разным классам. Проверка по значениям, а не по ключам: ключи уникальны сами.
    повторы = sorted(
        class_id for class_id, сколько in Counter(idx_to_class_id.values()).items() if сколько > 1
    )
    if повторы:
        raise ValueError(f"idx_to_class_id неинъективен: {повторы} под разными индексами")

    попаданий_1 = 0
    попаданий_5 = 0
    попаданий_марка = 0
    верных_в_классе: Counter[int] = Counter()
    всего_в_классе: Counter[int] = Counter()

    for номер, (предсказания, цель) in enumerate(zip(top5, targets, strict=True)):
        if len(предсказания) < TOP_K:
            raise ValueError(
                f"строка {номер}: {len(предсказания)} предсказаний, а top5 требует {TOP_K}"
            )
        всего_в_классе[цель] += 1
        if предсказания[0] == цель:
            попаданий_1 += 1
            верных_в_классе[цель] += 1
        if цель in предсказания[:TOP_K]:
            попаданий_5 += 1
        if марки_совпали(idx_to_brand[предсказания[0]], idx_to_brand[цель]):
            попаданий_марка += 1

    сколько = len(targets)
    return Metrics(
        top1_model=попаданий_1 / сколько,
        top5_model=попаданий_5 / сколько,
        top1_brand=попаданий_марка / сколько,
        per_class_recall={
            idx_to_class_id[индекс]: верных_в_классе[индекс] / всего
            for индекс, всего in sorted(всего_в_классе.items())
        },
    )
