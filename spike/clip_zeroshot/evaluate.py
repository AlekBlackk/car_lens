"""Арифметика замера: косинус к опорным векторам и доли попаданий по срезам.

Центроид у класса один (`centroids_per_class = 1`), но форма массива сохраняется
трёхмерной — той же, что у продакшн-индекса, чтобы код читался рядом с ним.
"""

from __future__ import annotations

import numpy as np


def topk_hits(
    эмбеддинги: np.ndarray, центроиды: np.ndarray, метки: np.ndarray, k: int
) -> np.ndarray:
    """Попал ли верный класс в top-k по косинусу. Возвращает булев массив длины N."""
    if k < 1:
        raise ValueError(f"k={k}: top-0 не бывает")
    классов = центроиды.shape[0]
    плоские = центроиды.reshape(классов * центроиды.shape[1], центроиды.shape[2])
    близость = эмбеддинги @ плоские.T
    # Максимум по центроидам класса: при одном центроиде это тождество, но форма
    # остаётся общей с продакшн-путём, где их четыре.
    по_классам = близость.reshape(len(эмбеддинги), классов, центроиды.shape[1]).max(axis=2)
    порядок = np.argsort(-по_классам, axis=1)[:, :k]
    return np.any(порядок == метки[:, None], axis=1)


def accuracy_by_class(
    попадания: np.ndarray, метки: np.ndarray, классов: int
) -> dict[int, float]:
    """Доля попаданий по каждому классу. Классы без единого фото в результат не входят."""
    результат: dict[int, float] = {}
    for класс in range(классов):
        маска = метки == класс
        всего = int(маска.sum())
        if всего == 0:
            continue
        результат[класс] = float(попадания[маска].sum()) / всего
    return результат
