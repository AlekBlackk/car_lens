package com.carlens.vision

import kotlin.math.min

/**
 * Выборка пикселей источника кадра сразу в тензор модели.
 *
 * Источник — `FrameSource`: плоскости YUV с камеры или готовые RGB-пиксели в тестах
 * паритета. Геометрия, поля и раскладка живут здесь и общие для обоих, различается
 * только чтение цвета — иначе тестовый путь проверял бы свою копию арифметики.
 *
 * Полный RGB-кадр не материализуется: промежуточный битмап — это лишний проход по
 * памяти на каждом кадре, и ровно на его отсутствии стоит отказ от NDK (§3 дизайна).
 * Выборка билинейная, потому что питоновский эталон и в ultralytics, и в `A.Resize`
 * валидации использует `cv2.INTER_LINEAR`; ближайший сосед сдвигает эмбеддинг ровно
 * настолько, чтобы паритет не сошёлся, а причину искали в квантизации.
 *
 * Обход тензора идёт плитками, а не строками, и это единственное, что отделяет 48 мс
 * препроцессинга (замер M-1.5, `bench/latency.md`) от нескольких. Причина — поворот
 * кадра: при `rotationDegrees = 90` координата сенсора по X зависит от **строки**
 * тензора, а по Y — от **столбца**, поэтому построчный обход тензора шёл по столбцу
 * буфера камеры, прыгая через `rowStride` на каждом пикселе. Двенадцать чтений на
 * пиксель (Y, U, V по четыре) — двенадцать промахов кэша, 173 тысячи раз за кадр.
 * Плитка 32x32 держит в кэше обе стороны: около 50x50 байт исходной области на
 * плоскость против 32x32 значений тензора. Арифметика при этом не меняется ни на бит —
 * меняется только порядок посещения пикселей.
 */
object FrameConvert {

    private const val БЕЗ_ПОЛЯ = -1

    /**
     * Сторона плитки обхода. 32 — не подгонка под устройство: при масштабе кадра порядка
     * единицы исходная область плитки укладывается примерно в 50x50 байт на плоскость,
     * то есть в пару десятков строк кэша, и остаётся там на все 32 столбца плитки.
     */
    private const val ПЛИТКА = 32

    /**
     * Вписать кадр целиком в квадратный тензор с серыми полями.
     *
     * Возвращает то же отображение, что `Letterbox.forFrame`: вызывающий разворачивает
     * им боксы обратно в координаты выпрямленного кадра.
     */
    fun letterbox(frame: FrameSource, spec: TensorSpec, padValue: Int, dst: FloatArray): Letterbox {
        require(dst.size >= spec.floatCount) {
            "буфер назначения ${dst.size} против ${spec.floatCount} по спецификации тензора"
        }
        require(padValue in 0..255) { "значение поля $padValue вне 0..255" }
        val выпрямленный = frame.upright
        val отображение = Letterbox.forFrame(выпрямленный, spec.size)
        val цвет = FloatArray(3)
        val сенсор = FloatArray(2)
        val раскладка = РаскладкаТензора(spec)
        // Угол нормализуется один раз на кадр, а не на пиксель: см. `toSensorIntoNormalized`.
        val угол = Rotation.нормализованный(frame.rotationDegrees)
        val масштаб = отображение.scale
        val полеX = отображение.padX
        val полеY = отображение.padY
        поПлиткам(spec.size) { строка, столбец ->
            val xВыпрямленный = (столбец + 0.5f - полеX) / масштаб - 0.5f
            val yВыпрямленный = (строка + 0.5f - полеY) / масштаб - 0.5f
            записать(
                frame, выпрямленный, раскладка, угол, dst,
                строка, столбец, xВыпрямленный, yВыпрямленный, padValue, цвет, сенсор,
            )
        }
        return отображение
    }

    /**
     * Растянуть область бокса на весь тензор — вход классификатора.
     *
     * Полей здесь нет: `Boxes.pad` уже обрезал область по кадру, а доли пикселя на краю
     * берутся зажатием координаты, а не серым, иначе кроп у края кадра получает рамку,
     * которой не было в обучающих кропах.
     */
    fun crop(frame: FrameSource, boxUpright: Box, pad: Float, spec: TensorSpec, dst: FloatArray) {
        require(dst.size >= spec.floatCount) {
            "буфер назначения ${dst.size} против ${spec.floatCount} по спецификации тензора"
        }
        val выпрямленный = frame.upright
        val область = Boxes.pad(boxUpright, выпрямленный.width, выпрямленный.height, pad)
        require(область.w > 0f && область.h > 0f) { "пустой бокс: ${область.w}×${область.h}" }
        val цвет = FloatArray(3)
        val сенсор = FloatArray(2)
        val раскладка = РаскладкаТензора(spec)
        val угол = Rotation.нормализованный(frame.rotationDegrees)
        val сторона = spec.size
        поПлиткам(сторона) { строка, столбец ->
            val xВыпрямленный = область.x + (столбец + 0.5f) * область.w / сторона - 0.5f
            val yВыпрямленный = область.y + (строка + 0.5f) * область.h / сторона - 0.5f
            записать(
                frame, выпрямленный, раскладка, угол, dst,
                строка, столбец, xВыпрямленный, yВыпрямленный, БЕЗ_ПОЛЯ, цвет, сенсор,
            )
        }
    }

    /**
     * Обход квадрата плитками: сначала плитка, внутри — её строки и столбцы.
     *
     * `inline`, потому что тело зовётся 173 тысячи раз за кадр: обычная лямбда стоила бы
     * здесь мегаморфного вызова на каждый пиксель.
     */
    private inline fun поПлиткам(сторона: Int, действие: (Int, Int) -> Unit) {
        var началоСтрок = 0
        while (началоСтрок < сторона) {
            val конецСтрок = min(началоСтрок + ПЛИТКА, сторона)
            var началоСтолбцов = 0
            while (началоСтолбцов < сторона) {
                val конецСтолбцов = min(началоСтолбцов + ПЛИТКА, сторона)
                for (строка in началоСтрок until конецСтрок) {
                    for (столбец in началоСтолбцов until конецСтолбцов) действие(строка, столбец)
                }
                началоСтолбцов = конецСтолбцов
            }
            началоСтрок = конецСтрок
        }
    }

    /**
     * Разобранная спецификация тензора: то же самое, что в `TensorSpec`, но полями, а не
     * `enum`/`sealed`.
     *
     * Разбирается один раз на кадр. В `TensorSpec` раскладка и нормализация — `enum` и
     * `sealed interface`, и на каждый из полумиллиона записанных значений это был бы
     * `instanceof` с загрузкой полей объекта из кучи там, где всё нужное — три булевых
     * флага и две ссылки на массив.
     *
     * Арифметика нормализации оставлена ровно той же, что была, вплоть до порядка
     * операций: свести `(v / 255 - mean) / std` к одному умножению со сдвигом означало бы
     * другое округление float, а паритет с питоновским эталоном проверяется по пикселям.
     */
    private class РаскладкаТензора(spec: TensorSpec) {
        val сторона = spec.size
        val плоскость = spec.size * spec.size
        val nchw = spec.layout == TensorLayout.NCHW
        val rgb = spec.channels == ChannelOrder.RGB
        val mean: FloatArray? = (spec.scaling as? Scaling.MeanStd)?.mean
        val std: FloatArray? = (spec.scaling as? Scaling.MeanStd)?.std
    }

    private fun записать(
        frame: FrameSource,
        выпрямленный: UprightSize,
        раскладка: РаскладкаТензора,
        угол: Int,
        dst: FloatArray,
        строка: Int,
        столбец: Int,
        xВыпрямленный: Float,
        yВыпрямленный: Float,
        padValue: Int,
        цвет: FloatArray,
        сенсор: FloatArray,
    ) {
        val внеКадра = xВыпрямленный < 0f || yВыпрямленный < 0f ||
            xВыпрямленный > выпрямленный.width - 1f || yВыпрямленный > выпрямленный.height - 1f
        if (внеКадра && padValue != БЕЗ_ПОЛЯ) {
            // Поле проходит ту же нормализацию, что и пиксели: для детектора это
            // 114/255 из ultralytics, а серый, не поделённый на 255, был бы ровно тем
            // тихим расхождением с эталоном, которое ищут потом в квантизации.
            val серый = padValue.toFloat()
            записатьПиксель(раскладка, dst, строка, столбец, серый, серый, серый)
            return
        }
        // Один вызов вместо sensorX+sensorY порознь: угол поворота — константа кадра, и
        // нормализовать его дважды на каждый из 173 тысяч пикселей незачем.
        Rotation.toSensorIntoNormalized(xВыпрямленный, yВыпрямленный, выпрямленный, угол, сенсор)
        frame.sampleRgb(сенсор[0], сенсор[1], цвет)
        записатьПиксель(раскладка, dst, строка, столбец, цвет[0], цвет[1], цвет[2])
    }

    private fun записатьПиксель(
        раскладка: РаскладкаТензора,
        dst: FloatArray,
        строка: Int,
        столбец: Int,
        красный: Float,
        зелёный: Float,
        синий: Float,
    ) {
        val первый = if (раскладка.rgb) красный else синий
        val третий = if (раскладка.rgb) синий else красный
        положить(раскладка, dst, строка, столбец, канал = 0, значение = первый)
        положить(раскладка, dst, строка, столбец, канал = 1, значение = зелёный)
        положить(раскладка, dst, строка, столбец, канал = 2, значение = третий)
    }

    /**
     * Нормализовать и положить одно значение.
     *
     * `mean`/`std` индексируются номером канала **в тензоре**, а не цветом: в
     * `export_report.json` они записаны в том порядке, в каком модель ждёт входы, и
     * `ChannelOrder` уже применён выше.
     */
    private fun положить(
        раскладка: РаскладкаТензора,
        dst: FloatArray,
        строка: Int,
        столбец: Int,
        канал: Int,
        значение: Float,
    ) {
        val mean = раскладка.mean
        val нормированное = if (mean == null) {
            значение / 255f
        } else {
            (значение / 255f - mean[канал]) / раскладка.std!![канал]
        }
        val смещение = if (раскладка.nchw) {
            канал * раскладка.плоскость + строка * раскладка.сторона + столбец
        } else {
            (строка * раскладка.сторона + столбец) * 3 + канал
        }
        dst[смещение] = нормированное
    }

}
