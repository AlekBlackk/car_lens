package com.carlens.vision

/**
 * Буферы моста, выданные по размеру и переиспользуемые на следующих вызовах.
 *
 * Зачем. Каждый `SharedArray` VisionCamera держит глобальную ссылку JNI и освобождает её,
 * только когда JS-рантайм соберёт мусор. В воркет-рантайме кадрового процессора сборка
 * идёт редко (давление создаёт нативная память, которую она не видит), поэтому плагин,
 * выделяющий массив на каждый кадр, к ~18 минутам работы камеры переполняет таблицу
 * глобальных ссылок (`max=51200`) и роняет процесс (`SIGABRT`, 2026-10-08, 0.8.1 на S23).
 *
 * Контракт тот же, что у слотов эмбеддинга: **содержимое действительно до следующего
 * вызова того же плагина**. JS-сторона (`plugins.ts`) читает ответ синхронно в том же
 * вызове воркета и копирует числа в обычные объекты, поэтому гонки нет. Размер выдаётся
 * ровно запрошенный: JS сверяет длину буфера с `count`, и буфер «с запасом» его не
 * пройдёт. Различных размеров мало (число боксов и совпадений ограничено), так что пул
 * остаётся в пределах десятка буферов.
 */
class BufferPool<T : Any>(private val создать: (Int) -> T) {
    private val выданные = HashMap<Int, T>()

    /** Буфер на `байт` байт: тот же объект, что выдавался прежде, либо новый при первом запросе. */
    @Synchronized
    fun взять(байт: Int): T = выданные.getOrPut(байт) { создать(байт) }

    /** Сколько разных буферов уже создано; растёт только вместе с числом разных размеров. */
    @get:Synchronized
    val создано: Int get() = выданные.size
}
