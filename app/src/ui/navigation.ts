/**
 * Навигация между экранами §6.6. Чистый редьюсер: про React, `BackHandler` и рендер
 * модуль не знает ничего.
 *
 * Стек, а не пара «текущий/предыдущий». Причина конкретная: путь глубины три достижим —
 * Детали открываются с замороженного кадра, а из Деталей кнопка «это неверно» при
 * выключенном opt-in ведёт в Настройки, — то есть `Камера → Детали → Настройки`. Возврат
 * по нему обязан идти через Детали, а пара из двух ссылок после первого же возврата уже
 * не помнит, откуда Детали открыли, и второй шаг назад ей пришлось бы угадывать.
 *
 * Переход «это неверно» → Настройки — решение UI, а не цитата спеки: §8 требует только
 * явный opt-in, выключенный по умолчанию и отключаемый в настройках, а куда ведёт кнопка
 * до согласия, спека не оговаривает.
 *
 * Пути `История → Детали` в приложении нет: строки Истории не нажимаются, она «только
 * текст» (§6.6), — поэтому История живёт на глубине два и в переполнение стека не
 * участвует иначе как жертва.
 */

export type Экран =
  | { вид: 'камера' }
  | { вид: 'детали'; трек: number }
  | { вид: 'история' }
  | { вид: 'настройки' }
  | { вид: 'каталог' }

export type СостояниеНавигации = { стек: Экран[] }

/** Экран камеры — константа на весь модуль: дно стека у всех состояний одно и то же. */
export const КАМЕРА: Экран = Object.freeze({ вид: 'камера' })

const СТЕК_СТАРТА: Экран[] = [КАМЕРА]
Object.freeze(СТЕК_СТАРТА)

/**
 * Заморозка адресована вызывающему, а не модулю: `push` при повторе того же экрана отдаёт
 * пришедшее состояние обратно по ссылке, поэтому `НАЧАЛЬНАЯ_НАВИГАЦИЯ` попадает наружу под
 * видом «нового состояния», и `состояние.стек.push(...)` в рендере испортил бы старт
 * приложения не на один экран, а на весь прогон процесса. Копию, в отличие от
 * `store/settings.ts`, редьюсер отдавать не может: на тождестве возвращаемого объекта
 * держится пропуск ре-рендера. Массив `стек` заморожен отдельно — заморозка объекта на
 * вложенный массив не распространяется, а испортить нужно было бы именно его.
 */
export const НАЧАЛЬНАЯ_НАВИГАЦИЯ: СостояниеНавигации = Object.freeze({ стек: СТЕК_СТАРТА })

/**
 * Предел глубины. Три — камера, откуда пришли, и текущий экран. Ограничение стоит не ради
 * памяти, а ради поведения: без него повторные переходы копили бы историю возвратов, и
 * пользователю пришлось бы жать «назад» столько же раз, сколько он нажал вперёд.
 *
 * Путь `Камера → Детали → Настройки → Каталог` длиннее предела: Детали из него вытесняются,
 * и «назад» из Каталога ведёт в Настройки, а затем сразу на камеру. Каталог — справочник,
 * а не часть сценария жалобы, и возвращать из него в Детали незачем.
 */
const ПРЕДЕЛ_ГЛУБИНЫ = 3

const тотЖе = (первый: Экран, второй: Экран): boolean => {
  if (первый.вид !== второй.вид) return false
  if (первый.вид === 'детали' && второй.вид === 'детали') return первый.трек === второй.трек
  return true
}

/** Экран, который сейчас показывается. Стек не бывает пустым, поэтому не `null`. */
export function верхний(состояние: СостояниеНавигации): Экран {
  return состояние.стек[состояние.стек.length - 1]!
}

/**
 * Переход. Повтор того же экрана не удлиняет стек: двойное нажатие не должно требовать
 * двух возвратов.
 *
 * При переполнении вырезается элемент с индексом 1, а не 0. Дно неприкосновенно: там
 * всегда камера, и вытолкнуть её значило бы и оставить приложение без экрана, на который
 * возвращаются, и лишить `pop` признака дна, по которому тот отдаёт `null`. Поэтому из
 * `[камера, A, B]` переход на `C` даёт `[камера, B, C]`: жертвой становится `A` — экран,
 * до которого возврат добрался бы позже всех, кроме камеры.
 *
 * На камеру возвращаются через `pop`, а не `push`: `push(КАМЕРА)` с не-камерного верха даёт
 * `[камера, X, камера]`, и следующее «назад» уведёт в `X` вместо выхода из приложения.
 */
export function push(состояние: СостояниеНавигации, экран: Экран): СостояниеНавигации {
  if (тотЖе(верхний(состояние), экран)) return состояние
  const стек = [...состояние.стек, экран]
  if (стек.length > ПРЕДЕЛ_ГЛУБИНЫ) стек.splice(1, стек.length - ПРЕДЕЛ_ГЛУБИНЫ)
  return { стек }
}

/**
 * Возврат. `null` на дне стека — сигнал вызывающему не перехватывать аппаратную кнопку и
 * дать системе закрыть приложение.
 */
export function pop(состояние: СостояниеНавигации): СостояниеНавигации | null {
  if (состояние.стек.length <= 1) return null
  return { стек: состояние.стек.slice(0, -1) }
}
