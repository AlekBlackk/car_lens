/**
 * Представление каталога для списков: поиск и группировка по маркам. Чистые функции —
 * экраны «Каталог» и выбор класса в жалобе делят одно правило поиска, а не по копии на экран.
 */
import type { Класс } from '../vision/labels'

/** Раздел для групп, у которых марки нет (§13.2): одной маркой «Geely Coolray / Belgee X50» не назвать. */
export const РАЗДЕЛ_БЕЗ_МАРКИ = 'Несколько марок'

export type РазделКаталога = {
  название: string
  data: readonly Класс[]
}

/**
 * Поиск идёт и по марке: пользователь, не знающий модель, ищет «toyota», а не «camry».
 * У разнобрендовой группы марки нет вовсе, и найти её по марке участника можно только через
 * `members`: `member_id` вида «belgee__x50» несёт и марку, и модель.
 */
export function подходитПодЗапрос(класс: Класс, запрос: string): boolean {
  const строка = запрос.trim().toLowerCase()
  if (строка.length === 0) return true
  return (
    класс.display.toLowerCase().includes(строка) ||
    (класс.brand?.toLowerCase().includes(строка) ?? false) ||
    класс.members.some((участник) => участник.toLowerCase().includes(строка))
  )
}

/**
 * Классы, подошедшие под запрос, по маркам. Марки идут по алфавиту, раздел без марки — в
 * конце; внутри марки порядок каталога сохраняется, потому что собран он уже по названию, а
 * сравнивать «Audi 80» с «Audi 100» через `localeCompare` значило бы зависеть от Intl
 * рантайма телефона. Пустые разделы не возвращаются.
 */
export function разделыКаталога(классы: readonly Класс[], запрос: string): РазделКаталога[] {
  const поМаркам = new Map<string | null, Класс[]>()
  for (const класс of классы) {
    if (!подходитПодЗапрос(класс, запрос)) continue
    const группа = поМаркам.get(класс.brand)
    if (группа === undefined) поМаркам.set(класс.brand, [класс])
    else группа.push(класс)
  }
  const разделы: РазделКаталога[] = []
  for (const [марка, группа] of поМаркам) {
    if (марка !== null) разделы.push({ название: марка, data: группа })
  }
  разделы.sort((первый, второй) => первый.название.localeCompare(второй.название))
  const безМарки = поМаркам.get(null)
  if (безМарки !== undefined) разделы.push({ название: РАЗДЕЛ_БЕЗ_МАРКИ, data: безМарки })
  return разделы
}
