/**
 * Текст подписи по решению §6.4. Отметка «не откалибровано» стоит, пока таблица калибровки
 * не размечена (`tuned: false`, §13.5): без неё плейсхолдер незаметно доживает до релиза и
 * выдаётся пользователю за измеренный процент.
 */
export const текстПодписи = (решение: Решение): string => {
  if (решение.kind === 'определяю') return 'Определяю…'
  if (решение.kind === 'ближе') return 'Подойдите ближе'
  if (решение.kind === 'неизвестно') return 'Не узнаю'
  if (решение.kind === 'бренд') return classLabel(решение.classIdx)?.brand ?? 'Не узнаю'
  const имя = classLabel(решение.classIdx)?.display ?? `класс ${решение.classIdx}`
  const процент = Math.round(решение.confidence * 100)
  return решение.calibrated ? `${имя} · ${процент}%` : `${имя} · ${процент}% (не откалибровано)`
}

/**
 * Одна запись в историю на трек, а не на кадр: подпись пересчитывается каждым кадром, и без
 * этого множества одна и та же машина падала бы в историю восемь раз в секунду.
 *
 * Признак «то же самое» — id трека: сама запись его не хранит (§6.6 — только текст), а
 * сравнение по `classIdx` склеило бы две одинаковые машины в кадре в одну строку.
 *
 * Код живёт в React-обработчике, а не в воркете, поэтому `Set` и `for...of` здесь допустимы.
 */
function записатьРаспознанное(
  подписи: ПодписьТрека[],
  записанные: Set<number>,
  наРаспознавание: (запись: ЗаписьИстории) => void,
): void {
  const каталог = catalogDigest()
  const живые = new Set<number>()
  for (const подпись of подписи) {
    живые.add(подпись.id)
    if (записанные.has(подпись.id)) continue
    const запись = записьИзРешения(подпись.decision, Date.now(), каталог)
    if (запись === null) continue
    записанные.add(подпись.id)
    наРаспознавание(запись)
  }
  // Умершие треки выпадают из множества, иначе оно растёт весь сеанс.
  for (const id of Array.from(записанные)) {
    if (!живые.has(id)) записанные.delete(id)
  }
}

