/**
 * Экран «Детали» §6.6: что именно модель увидела в этом треке и жалоба на подпись (§8).
 *
 * Открывается только с замороженного кадра — по тапу в рамку. Поэтому подпись сюда приходит
 * снимком, а не подпиской: на замороженном кадре конвейер стоит, и пересчитывать нечего.
 *
 * **Заголовок и строки гипотез намеренно из разных мест, но не про разное.** Заголовок —
 * `текстПодписи(подпись.решение)`, то есть ровно та строка, которую пользователь видел на
 * кадре, уже после пользовательского порога. Строки ниже — сырые гипотезы моста, до порога.
 * Расхождение между ними возможно: при пороге 0.7 и уверенности 0.62 сверху стоит «Не
 * узнаю», а ниже — «Toyota Camry · 62%». Это не противоречие, а единственная причина, по
 * которой экран существует: он показывает, что видит модель, когда подпись не показана.
 * Чтобы читатель не гадал, отчего заголовок молчит, над строками встаёт объяснение — см.
 * `скрытоПорогом` в `vision/userThreshold.ts`. Глушить гипотезы порогом заодно значило бы
 * оставить пользователю пустой экран ровно в том случае, ради которого он его открыл.
 */
import React, { useState } from 'react'
import { Pressable, ScrollView, StyleSheet, Text, View } from 'react-native'
import { записатьОтзыв } from '../../store/feedback'
import type { Настройки } from '../../store/settings'
import type { Хранилище } from '../../store/storage'
import { catalogDigest, classLabel } from '../../vision/labels'
import type { ПодписьТрека } from '../../vision/pipeline'
import { CALIBRATION, THRESHOLDS, confidenceFromSim } from '../../vision/thresholds'
import { скрытоПорогом } from '../../vision/userThreshold'
import ClassPicker from './ClassPicker'
import { текстПодписи } from './CameraScreen'

export type СвойстваДеталей = {
  подпись: ПодписьТрека | null
  настройки: Настройки
  хранилище: Хранилище
  наНастройки: () => void
  наЗакрытие: () => void
}

/** Пока хотя бы один ассет не размечен, любое число обязано нести оговорку (§13.5). */
const ОТКАЛИБРОВАНО = THRESHOLDS.tuned && CALIBRATION.tuned

export default function DetailsScreen(свойства: СвойстваДеталей): React.JSX.Element {
  const { подпись, настройки, хранилище, наНастройки, наЗакрытие } = свойства
  const [списокОткрыт, установитьСписок] = useState(false)
  const [жалобаЗаписана, установитьЖалобуЗаписана] = useState(false)

  if (подпись === null) {
    // Разыменовывать исчезнувший трек нельзя, а молчаливый пустой экран хуже надписи.
    return (
      <View style={styles.экран}>
        <Text style={styles.заголовок}>Трек потерян</Text>
        <Pressable onPress={наЗакрытие}>
          <Text style={styles.кнопка}>Назад</Text>
        </Pressable>
      </View>
    )
  }

  if (списокОткрыт) {
    return (
      <ClassPicker
        наВыбор={(classIdx) => {
          const первая = подпись.топы.length > 0 ? подпись.топы[0]! : null
          // Возвращённое значение, а не предположение: `записатьОтзыв` — воронка §8, и
          // при выключенном opt-in она ничего не пишет. Сказать «записана» в этом случае
          // значило бы соврать ровно там, где спека требует честности.
          const легло = записатьОтзыв(
            хранилище,
            {
              время: Date.now(),
              каталог: catalogDigest(),
              предсказанный: первая?.classIdx ?? -1,
              правильный: classIdx,
              sim: первая?.sim ?? 0,
              bbox: [подпись.бокс.x, подпись.бокс.y, подпись.бокс.w, подпись.бокс.h],
            },
            настройки.сборОбратнойСвязи,
          )
          установитьСписок(false)
          установитьЖалобуЗаписана(легло)
        }}
        наОтмену={() => установитьСписок(false)}
      />
    )
  }

  const гипотезы = настройки.показыватьТоп3 ? подпись.топы : подпись.топы.slice(0, 1)

  return (
    <ScrollView style={styles.экран} contentContainerStyle={styles.содержимое}>
      <Text style={styles.заголовок}>{текстПодписи(подпись.решение)}</Text>

      {скрытоПорогом(
        подпись.решение,
        подпись.топы.length > 0 ? подпись.топы[0]! : null,
        настройки.порогУверенности,
        THRESHOLDS,
        CALIBRATION,
      ) && (
        <Text style={styles.пояснение}>
          Подпись скрыта вашим порогом ({Math.round(настройки.порогУверенности * 100)}%).
          Гипотезы ниже показаны как есть.
        </Text>
      )}

      {гипотезы.length === 0 ? (
        <Text style={styles.пояснение}>Модель ещё не успела рассмотреть этот трек.</Text>
      ) : (
        гипотезы.map((матч) => {
          const класс = classLabel(матч.classIdx)
          const процент = Math.round(confidenceFromSim(матч.sim, CALIBRATION) * 100)
          return (
            <Text key={матч.classIdx} style={styles.строка}>
              {класс?.display ?? `класс ${матч.classIdx}`} · {класс?.brand ?? '—'} · sim{' '}
              {матч.sim.toFixed(3)} · {процент}%{ОТКАЛИБРОВАНО ? '' : ' (не откалибровано)'}
            </Text>
          )
        })
      )}

      {жалобаЗаписана ? (
        <Text style={styles.пояснение}>Жалоба записана и останется на телефоне.</Text>
      ) : (
        <Pressable
          onPress={() => (настройки.сборОбратнойСвязи ? установитьСписок(true) : наНастройки())}
        >
          <Text style={styles.кнопка}>Это неверно</Text>
        </Pressable>
      )}
      {!настройки.сборОбратнойСвязи && (
        // Собрать жалобу и выбросить её было бы враньём пользователю; показать, где
        // включается сбор, — нет.
        <Text style={styles.пояснение}>
          Сбор жалоб выключен. Включить можно в настройках — данные останутся на телефоне.
        </Text>
      )}

      <Pressable onPress={наЗакрытие}>
        <Text style={styles.кнопка}>Назад</Text>
      </Pressable>
    </ScrollView>
  )
}

const styles = StyleSheet.create({
  экран: { flex: 1, backgroundColor: '#000' },
  содержимое: { paddingHorizontal: 20, paddingVertical: 24 },
  заголовок: { color: '#fff', fontSize: 22, marginBottom: 16 },
  строка: { color: '#fff', fontSize: 16, marginBottom: 8 },
  пояснение: { color: '#9a9a9a', fontSize: 15, marginBottom: 16, lineHeight: 21 },
  кнопка: { color: '#4da3ff', fontSize: 18, marginTop: 16 },
})
