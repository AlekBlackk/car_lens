import { describe, expect, it } from 'vitest'
import { КАМЕРА, НАЧАЛЬНАЯ_НАВИГАЦИЯ, верхний, pop, push, type Экран } from './navigation'

const детали = (трек: number): Экран => ({ вид: 'детали', трек })
const история: Экран = { вид: 'история' }
const настройки: Экран = { вид: 'настройки' }

describe('навигация', () => {
  it('начинается на камере', () => {
    expect(верхний(НАЧАЛЬНАЯ_НАВИГАЦИЯ)).toEqual(КАМЕРА)
  })

  it('переходит на каждый экран и возвращается', () => {
    for (const экран of [детали(7), история, настройки]) {
      const после = push(НАЧАЛЬНАЯ_НАВИГАЦИЯ, экран)
      expect(верхний(после)).toEqual(экран)
      const назад = pop(после)
      expect(назад).not.toBeNull()
      expect(верхний(назад!)).toEqual(КАМЕРА)
    }
  })

  it('на дне стека pop возвращает null', () => {
    expect(pop(НАЧАЛЬНАЯ_НАВИГАЦИЯ)).toBeNull()
  })

  it('путь Камера → Детали → Настройки возвращается через Детали, а не сразу на дно', () => {
    let состояние = push(НАЧАЛЬНАЯ_НАВИГАЦИЯ, детали(3))
    состояние = push(состояние, настройки)

    состояние = pop(состояние)!
    expect(верхний(состояние)).toEqual(детали(3))
    состояние = pop(состояние)!
    expect(верхний(состояние)).toEqual(КАМЕРА)
    expect(pop(состояние)).toBeNull()
  })

  it('повторный push того же экрана не удлиняет стек', () => {
    const один = push(НАЧАЛЬНАЯ_НАВИГАЦИЯ, настройки)
    const два = push(один, настройки)
    expect(два.стек).toHaveLength(2)
    expect(два).toBe(один)
    expect(pop(два)).not.toBeNull()
    expect(верхний(pop(два)!)).toEqual(КАМЕРА)
  })

  it('повторный push деталей другого трека — это новый экран', () => {
    const один = push(НАЧАЛЬНАЯ_НАВИГАЦИЯ, детали(1))
    const два = push(один, детали(2))
    expect(два.стек).toHaveLength(3)
    expect(верхний(два)).toEqual(детали(2))
  })

  it('стек не растёт выше трёх, дно остаётся камерой', () => {
    // Тройка собрана синтетически: путь История → Детали в приложении не нажимается, и
    // переполнения по достижимым переходам не бывает. Проверяется защитное поведение
    // редьюсера, если такой переход когда-нибудь появится, а не реальный сценарий.
    let состояние = push(push(НАЧАЛЬНАЯ_НАВИГАЦИЯ, история), детали(1))
    expect(состояние.стек).toEqual([КАМЕРА, история, детали(1)])

    состояние = push(состояние, настройки)
    expect(состояние.стек).toEqual([КАМЕРА, детали(1), настройки])

    for (const экран of [история, детали(2)]) {
      состояние = push(состояние, экран)
      expect(состояние.стек).toHaveLength(3)
      expect(состояние.стек[0]).toEqual(КАМЕРА)
    }
    expect(состояние.стек).toEqual([КАМЕРА, история, детали(2)])
  })
})
