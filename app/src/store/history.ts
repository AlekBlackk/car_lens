import { catalogDigest } from '../vision/labels'
import type { Решение } from '../vision/decide'
import { записатьJson, прочитатьJson, type Хранилище } from './storage'

/** §6.6 спеки: последние 50 распознаваний, локально, только текст, без изображений. */
export const ПРЕДЕЛ_ИСТОРИИ = 50

const КЛЮЧ = 'история'

export type ЗаписьИстории = {
  время: number
  /** digest каталога: `classIdx` осмыслен только внутри своей версии (§6.5 дизайна). */
  каталог: string
  classIdx: number
  вид: 'модель' | 'бренд'
  уверенность: number | null
  откалибровано: boolean
}

/**
 * Историей являются только распознавания. «Определяю», «подойдите ближе» и «не узнаю» —
 * состояния процесса, а не результаты, и в списке последних пятидесяти им делать нечего.
 */
export function записьИзРешения(
  решение: Решение,
  время: number,
  каталог: string,
): ЗаписьИстории | null {
  if (решение.вид === 'модель') {
    return {
      время,
      каталог,
      classIdx: решение.classIdx,
      вид: 'модель',
      уверенность: решение.уверенность,
      откалибровано: решение.откалибровано,
    }
  }
  if (решение.вид === 'бренд') {
    return {
      время,
      каталог,
      classIdx: решение.classIdx,
      вид: 'бренд',
      уверенность: null,
      откалибровано: false,
    }
  }
  return null
}

export function добавить(история: ЗаписьИстории[], запись: ЗаписьИстории): ЗаписьИстории[] {
  return [запись, ...история].slice(0, ПРЕДЕЛ_ИСТОРИИ)
}

/** Запись чужого каталога не разворачивается в имя: тот же `classIdx` там значит другое. */
export function своя(запись: ЗаписьИстории, каталог: string = catalogDigest()): boolean {
  return запись.каталог === каталог
}

const записьВалидна = (значение: unknown): значение is ЗаписьИстории => {
  const поля = значение as Record<string, unknown>
  return (
    typeof поля?.время === 'number' &&
    Number.isFinite(поля.время) &&
    typeof поля.каталог === 'string' &&
    typeof поля.classIdx === 'number' &&
    Number.isInteger(поля.classIdx) &&
    (поля.вид === 'модель' || поля.вид === 'бренд') &&
    (поля.уверенность === null || typeof поля.уверенность === 'number') &&
    typeof поля.откалибровано === 'boolean'
  )
}

export function разобратьИсторию(сырое: unknown): ЗаписьИстории[] {
  if (!Array.isArray(сырое)) return []
  return сырое.filter(записьВалидна).slice(0, ПРЕДЕЛ_ИСТОРИИ)
}

export function прочитатьИсторию(хранилище: Хранилище): ЗаписьИстории[] {
  return прочитатьJson(хранилище, КЛЮЧ, разобратьИсторию, [])
}

export function записатьИсторию(хранилище: Хранилище, история: ЗаписьИстории[]): void {
  записатьJson(хранилище, КЛЮЧ, история.slice(0, ПРЕДЕЛ_ИСТОРИИ))
}
