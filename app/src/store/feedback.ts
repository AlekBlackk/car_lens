import { записатьJson, прочитатьJson, type Хранилище } from './storage'

const КЛЮЧ = 'отзывы'

/**
 * Потолок очереди. Отправки в MVP нет (§9: никакого INTERNET), поэтому без предела
 * очередь на устройстве росла бы вечно.
 */
export const ПРЕДЕЛ_ОЧЕРЕДИ = 200

/**
 * Время, digest каталога и четвёрка §8 — но `bbox` хранится целиком: `[x, y, w, h]` в долях кадра,
 * то есть вместе с положением, тогда как §8 («что уходит») разрешает отправлять только размер.
 * Форма записи задана планом, и пока она честна: уходить некуда — в релизе нет INTERNET (§9), — а
 * на этом этапе очередь только пополняется и очищается, положение никто не читает.
 *
 * Отсюда обязательство тому, кто первым начнёт эту очередь отправлять: свести `bbox` к размеру
 * (`w`, `h`) до того, как что-либо покинет устройство. Положение автомобиля в кадре говорит о
 * съёмке, а не о слабых местах каталога, и §8 отправлять его не разрешал. Изображений здесь нет
 * и не будет.
 */
export type ЗаписьОтзыва = {
  время: number
  каталог: string
  предсказанный: number
  правильный: number
  sim: number
  bbox: [number, number, number, number]
}

export function добавитьОтзыв(очередь: ЗаписьОтзыва[], отзыв: ЗаписьОтзыва): ЗаписьОтзыва[] {
  return [отзыв, ...очередь].slice(0, ПРЕДЕЛ_ОЧЕРЕДИ)
}

const отзывВалиден = (значение: unknown): значение is ЗаписьОтзыва => {
  const поля = значение as Record<string, unknown>
  const bbox = поля?.bbox
  return (
    typeof поля?.время === 'number' &&
    Number.isFinite(поля.время) &&
    typeof поля.каталог === 'string' &&
    // `предсказанный` и `правильный` — это `classIdx`: дробное или бесконечное значение станет
    // промахом по индексу у того, кто развернёт запись в имя. Одного `typeof` мало — свои
    // документы пишет `JSON.stringify`, где `Infinity` превратился бы в `null`, но валидация
    // читает и чужие, а `JSON.parse('1e999')` даёт `Infinity`, и по типу это число.
    Number.isInteger(поля.предсказанный) &&
    Number.isInteger(поля.правильный) &&
    typeof поля.sim === 'number' &&
    Number.isFinite(поля.sim) &&
    Array.isArray(bbox) &&
    bbox.length === 4 &&
    bbox.every((число) => typeof число === 'number' && Number.isFinite(число))
  )
}

export function прочитатьОчередь(хранилище: Хранилище): ЗаписьОтзыва[] {
  return прочитатьJson(
    хранилище,
    КЛЮЧ,
    // Срез и на чтении, как у истории (`разобратьИсторию`): нормальным путём документ длиннее
    // предела не появится — писатель один и ходит через `добавитьОтзыв`, — но миграция, ручная
    // правка или снижение потолка в будущей версии оставят переросшую очередь лежать.
    (сырое) => (Array.isArray(сырое) ? сырое.filter(отзывВалиден).slice(0, ПРЕДЕЛ_ОЧЕРЕДИ) : []),
    [],
  )
}

/**
 * Возвращает `true`, если запись действительно легла. Решает не этот модуль: `разрешено` — это
 * `сборОбратнойСвязи` из настроек (§8: явный opt-in, по умолчанию `false`), и решение принимает
 * вызывающий. Здесь стоит воронка: другого писателя под `КЛЮЧ` нет — открытого аналога
 * `записатьИсторию` не завели осознанно, — поэтому до очереди нельзя добраться мимо этой проверки.
 */
export function записатьОтзыв(
  хранилище: Хранилище,
  отзыв: ЗаписьОтзыва,
  разрешено: boolean,
): boolean {
  if (!разрешено) return false
  записатьJson(хранилище, КЛЮЧ, добавитьОтзыв(прочитатьОчередь(хранилище), отзыв))
  return true
}

/**
 * Зовётся при выключении opt-in в настройках. Иначе «выключено» означало бы «уже
 * собранное продолжает лежать», а пользователь понимает под этим другое.
 */
export function очиститьОчередь(хранилище: Хранилище): void {
  хранилище.удалить(КЛЮЧ)
}
