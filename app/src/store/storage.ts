/**
 * Граница между «что хранит» и «где хранит». Всё, что пишет на диск, принимает
 * `Хранилище` параметром: тесты подставляют реализацию на `Map`, приложение — MMKV.
 * Ни один чистый модуль не импортирует `react-native-mmkv` — в node-окружении он не
 * грузится вовсе, и vitest пришлось бы учить его мокать.
 */
export interface Хранилище {
  прочитать(ключ: string): string | null
  записать(ключ: string, значение: string): void
  удалить(ключ: string): void
}

export class ХранилищеВПамяти implements Хранилище {
  private данные = new Map<string, string>()

  прочитать(ключ: string): string | null {
    return this.данные.get(ключ) ?? null
  }

  записать(ключ: string, значение: string): void {
    this.данные.set(ключ, значение)
  }

  удалить(ключ: string): void {
    this.данные.delete(ключ)
  }
}

/**
 * Битое содержимое не бросает, а откатывается к значению по умолчанию. Это осознанное
 * отличие от ассетов (`thresholds.ts`), которым падать положено: ассет описывает
 * поведение распознавания, а хранилище — только интерфейс, и потерянная история не
 * повод не запускать приложение.
 */
export function прочитатьJson<T>(
  хранилище: Хранилище,
  ключ: string,
  разобрать: (сырое: unknown) => T,
  поумолчанию: T,
): T {
  const сырое = хранилище.прочитать(ключ)
  if (сырое === null) return поумолчанию
  try {
    return разобрать(JSON.parse(сырое))
  } catch {
    return поумолчанию
  }
}

export function записатьJson(хранилище: Хранилище, ключ: string, значение: unknown): void {
  хранилище.записать(ключ, JSON.stringify(значение))
}
