import { describe, expect, it } from 'vitest'
import { ХранилищеВПамяти, записатьJson, прочитатьJson } from './storage'

describe('хранилище в памяти', () => {
  it('читает записанное и забывает удалённое', () => {
    const хранилище = new ХранилищеВПамяти()
    expect(хранилище.прочитать('нет')).toBeNull()
    хранилище.записать('ключ', 'значение')
    expect(хранилище.прочитать('ключ')).toBe('значение')
    хранилище.удалить('ключ')
    expect(хранилище.прочитать('ключ')).toBeNull()
  })
})

describe('json поверх хранилища', () => {
  const разобрать = (сырое: unknown): number[] => (Array.isArray(сырое) ? сырое.map(Number) : [])

  it('на пустом ключе отдаёт значение по умолчанию', () => {
    const хранилище = new ХранилищеВПамяти()
    expect(прочитатьJson(хранилище, 'к', разобрать, [1])).toEqual([1])
  })

  it('битый JSON не бросает, а отдаёт значение по умолчанию', () => {
    const хранилище = new ХранилищеВПамяти()
    хранилище.записать('к', '{не json')
    expect(прочитатьJson(хранилище, 'к', разобрать, [2])).toEqual([2])
  })

  it('записанное читается обратно', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьJson(хранилище, 'к', [3, 4])
    expect(прочитатьJson(хранилище, 'к', разобрать, [])).toEqual([3, 4])
  })
})
