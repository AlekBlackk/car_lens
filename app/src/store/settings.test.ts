import { describe, expect, it } from 'vitest'
import { ХранилищеВПамяти } from './storage'
import {
  МАКСИМУМ_ПОРОГА,
  НАСТРОЙКИ_ПО_УМОЛЧАНИЮ,
  записатьНастройки,
  прочитатьНастройки,
  разобратьНастройки,
} from './settings'

describe('настройки по умолчанию', () => {
  it('порог не фильтрует, топ-3 показывается, сбор выключен', () => {
    expect(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ).toEqual({
      порогУверенности: 0,
      показыватьТоп3: true,
      сборОбратнойСвязи: false,
    })
  })
})

describe('разбор настроек', () => {
  it('читает валидный документ целиком', () => {
    expect(
      разобратьНастройки({ порогУверенности: 0.5, показыватьТоп3: false, сборОбратнойСвязи: true }),
    ).toEqual({ порогУверенности: 0.5, показыватьТоп3: false, сборОбратнойСвязи: true })
  })

  it('порог вне диапазона заменяется значением по умолчанию', () => {
    expect(разобратьНастройки({ порогУверенности: -1 }).порогУверенности).toBe(0)
    expect(разобратьНастройки({ порогУверенности: 1.5 }).порогУверенности).toBe(0)
    expect(разобратьНастройки({ порогУверенности: Number.NaN }).порогУверенности).toBe(0)
  })

  it('верхняя граница допустима', () => {
    expect(разобратьНастройки({ порогУверенности: МАКСИМУМ_ПОРОГА }).порогУверенности).toBe(
      МАКСИМУМ_ПОРОГА,
    )
  })

  it('поле неверного типа заменяется значением по умолчанию', () => {
    expect(разобратьНастройки({ показыватьТоп3: 'да' }).показыватьТоп3).toBe(true)
  })

  it('неизвестное поле игнорируется', () => {
    expect(разобратьНастройки({ ерунда: 1 })).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  })

  it('не объект — значения по умолчанию', () => {
    expect(разобратьНастройки(null)).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
    expect(разобратьНастройки('строка')).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  })
})

describe('хранилище настроек', () => {
  it('записанное читается обратно', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьНастройки(хранилище, { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ, порогУверенности: 0.4 })
    expect(прочитатьНастройки(хранилище).порогУверенности).toBe(0.4)
  })

  it('битый JSON не бросает', () => {
    const хранилище = new ХранилищеВПамяти()
    хранилище.записать('настройки', '{сломано')
    expect(прочитатьНастройки(хранилище)).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  })
})
