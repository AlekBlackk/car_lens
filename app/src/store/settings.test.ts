import { describe, expect, it } from 'vitest'
import { ХранилищеВПамяти } from './storage'
import {
  МАКСИМУМ_ПОРОГА,
  НАСТРОЙКИ_ПО_УМОЛЧАНИЮ,
  записатьНастройки,
  прочитатьНастройки,
  разобратьНастройки,
} from './settings'

describe('настройки по умолчанию', () => {
  it('порог не фильтрует, топ-3 показывается, сбор выключен', () => {
    expect(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ).toEqual({
      порогУверенности: 0,
      показыватьТоп3: true,
      сборОбратнойСвязи: false,
    })
  })

  it('мутация выданных настроек не переписывает значения по умолчанию', () => {
    // Тип `Настройки` обещает изменяемый объект, поэтому править полученное вызывающему
    // можно — читатели и обязаны отдавать копию. Проверяются обе ветки, где прежде наружу
    // уходила сама константа: не-объект у разбора и промах по ключу у чтения.
    const разобранные = разобратьНастройки(null)
    разобранные.порогУверенности = 0.5
    const прочитанные = прочитатьНастройки(new ХранилищеВПамяти())
    прочитанные.порогУверенности = 0.6
    expect(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.порогУверенности).toBe(0)
  })

  it('сама константа заморожена', () => {
    // Страховка не для вызывающих, а от модуля, который полезет править default напрямую,
    // минуя читателей с их копиями.
    expect(Object.isFrozen(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)).toBe(true)
  })
})

describe('разбор настроек', () => {
  it('читает валидный документ целиком', () => {
    expect(
      разобратьНастройки({ порогУверенности: 0.5, показыватьТоп3: false, сборОбратнойСвязи: true }),
    ).toEqual({ порогУверенности: 0.5, показыватьТоп3: false, сборОбратнойСвязи: true })
  })

  it('порог вне диапазона заменяется значением по умолчанию', () => {
    expect(разобратьНастройки({ порогУверенности: -1 }).порогУверенности).toBe(0)
    expect(разобратьНастройки({ порогУверенности: 1.5 }).порогУверенности).toBe(0)
    expect(разобратьНастройки({ порогУверенности: Number.NaN }).порогУверенности).toBe(0)
  })

  it('верхняя граница допустима', () => {
    // Литерал, а не сама константа: иначе тест самореферентен и смена потолка на 1.0 осталась
    // бы зелёной, хотя план называет 0.9 фиксированным значением.
    expect(МАКСИМУМ_ПОРОГА).toBe(0.9)
    expect(разобратьНастройки({ порогУверенности: МАКСИМУМ_ПОРОГА }).порогУверенности).toBe(
      МАКСИМУМ_ПОРОГА,
    )
  })

  it('поле неверного типа заменяется значением по умолчанию', () => {
    expect(разобратьНастройки({ показыватьТоп3: 'да' }).показыватьТоп3).toBe(true)
    // §8 спеки: у сбора обратной связи мусор в поле не имеет права превратиться во
    // включённый opt-in — из всех флагов только у этого есть цена для приватности.
    expect(разобратьНастройки({ сборОбратнойСвязи: 'да' }).сборОбратнойСвязи).toBe(false)
  })

  it('неизвестное поле игнорируется', () => {
    expect(разобратьНастройки({ ерунда: 1 })).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  })

  it('не объект — значения по умолчанию', () => {
    expect(разобратьНастройки(null)).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
    expect(разобратьНастройки('строка')).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  })

  it('массив разбирается по полям и даёт значения по умолчанию', () => {
    // `typeof [] === 'object'` и это не `null`, поэтому массив охрану контейнера проходит и
    // разбирается по полям, которых у него нет. Итог верный, тест закрепляет именно его.
    expect(разобратьНастройки([])).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  })
})

describe('хранилище настроек', () => {
  it('записанное читается обратно', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьНастройки(хранилище, { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ, порогУверенности: 0.4 })
    expect(прочитатьНастройки(хранилище).порогУверенности).toBe(0.4)
  })

  it('документ под ключом «настройки» доходит до разбора', () => {
    const хранилище = new ХранилищеВПамяти()
    // Литерал ключа здесь не дублирование, а привязка: опечатка в `КЛЮЧ` осталась бы зелёной,
    // потому что промах по ключу отдаёт те же значения по умолчанию, что и сработавшая
    // валидация. Порог заведомо не дефолтный — только он и отличает эти два случая.
    const документ = { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ, порогУверенности: 0.7 }
    хранилище.записать('настройки', JSON.stringify(документ))
    expect(прочитатьНастройки(хранилище).порогУверенности).toBe(0.7)
  })

  it('битый JSON не бросает', () => {
    const хранилище = new ХранилищеВПамяти()
    хранилище.записать('настройки', '{сломано')
    expect(прочитатьНастройки(хранилище)).toEqual(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  })
})
