import { describe, expect, it } from 'vitest'
import { ХранилищеВПамяти } from './storage'
import {
  ПРЕДЕЛ_ОЧЕРЕДИ,
  добавитьОтзыв,
  записатьОтзыв,
  очиститьОчередь,
  прочитатьОчередь,
  type ЗаписьОтзыва,
} from './feedback'

const отзыв = (время: number): ЗаписьОтзыва => ({
  время,
  каталог: '1:abcdef012345:171',
  предсказанный: 4,
  правильный: 9,
  sim: 0.61,
  bbox: [0.1, 0.2, 0.3, 0.4],
})

/**
 * Сырой JSON, а не `JSON.stringify` от объекта: `Infinity` нужен как текст `1e999`. Собственный
 * `JSON.stringify` превратил бы его в `null`, и охрану по типу такая запись не прошла бы вовсе —
 * то есть проверялась бы не та ветка. Чужой документ приходит именно текстом.
 */
const сырая = (правки: Partial<Record<keyof ЗаписьОтзыва, string>> = {}): string => {
  const поля: Record<string, string> = {
    время: '1',
    каталог: '"1:abcdef012345:171"',
    предсказанный: '4',
    правильный: '9',
    sim: '0.61',
    bbox: '[0.1,0.2,0.3,0.4]',
    ...правки,
  }
  const пары = Object.entries(поля).map(([имя, значение]) => `"${имя}":${значение}`)
  return `{${пары.join(',')}}`
}

describe('очередь отзывов', () => {
  it('при выключенном opt-in ничего не пишется', () => {
    const хранилище = new ХранилищеВПамяти()
    expect(записатьОтзыв(хранилище, отзыв(1), false)).toBe(false)
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })

  it('при включённом opt-in запись ложится и читается', () => {
    const хранилище = new ХранилищеВПамяти()
    expect(записатьОтзыв(хранилище, отзыв(1), true)).toBe(true)
    expect(прочитатьОчередь(хранилище)).toEqual([отзыв(1)])
  })

  it('digest каталога сохраняется в записи', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьОтзыв(хранилище, отзыв(1), true)
    expect(прочитатьОчередь(хранилище)[0]!.каталог).toBe('1:abcdef012345:171')
  })

  it('на пределе вытесняется самая старая', () => {
    let очередь: ЗаписьОтзыва[] = []
    for (let номер = 0; номер < ПРЕДЕЛ_ОЧЕРЕДИ + 1; номер++) {
      очередь = добавитьОтзыв(очередь, отзыв(номер))
    }
    expect(очередь).toHaveLength(ПРЕДЕЛ_ОЧЕРЕДИ)
    expect(очередь[очередь.length - 1]!.время).toBe(1)
  })

  it('очистка стирает всё', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьОтзыв(хранилище, отзыв(1), true)
    очиститьОчередь(хранилище)
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })

  it('мусор в хранилище даёт пустую очередь', () => {
    const хранилище = new ХранилищеВПамяти()
    // Сначала живая запись под тем же литеральным ключом: без неё промах по ключу выглядел бы
    // точно так же, как сработавшая валидация, — пустая очередь и зелёный тест при опечатке
    // в `КЛЮЧ`.
    хранилище.записать('отзывы', JSON.stringify([отзыв(1)]))
    expect(прочитатьОчередь(хранилище)).toEqual([отзыв(1)])
    хранилище.записать('отзывы', '{"не":"массив"}')
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })

  it('мутация пустой очереди не отравляет следующее чтение', () => {
    // `прочитатьJson` отдаёт четвёртый аргумент как есть, не проводя его через разбор, — и на
    // промахе по ключу, и на битом JSON. Общий массив на все вызовы копил бы чужие правки.
    const хранилище = new ХранилищеВПамяти()
    прочитатьОчередь(хранилище).push(отзыв(1))
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })

  it('битая запись выбрасывается, валидный сосед остаётся', () => {
    const хранилище = new ХранилищеВПамяти()
    const документ = (битая: string): string => `[${JSON.stringify(отзыв(1))},${битая}]`

    // Шаблон `сырая()` без правок обязан проходить валидацию: иначе опечатка в самом шаблоне
    // делала бы зелёными все проверки ниже — брак находился бы не там, где его подложили.
    хранилище.записать('отзывы', документ(сырая()))
    expect(прочитатьОчередь(хранилище)).toHaveLength(2)

    // Числа проверяются на конечность и целость, а не только на `typeof`: `1e999` разбирается в
    // `Infinity`, а `предсказанный` и `правильный` — это `classIdx`, которым дробное значение
    // означает промах по индексу каталога у того, кто развернёт запись в имя.
    const брак: [string, string][] = [
      ['полей нет вовсе', '{"время":"вчера"}'],
      ['время не число', сырая({ время: '"вчера"' })],
      ['время бесконечно', сырая({ время: '1e999' })],
      ['sim бесконечен', сырая({ sim: '1e999' })],
      ['предсказанный дробный', сырая({ предсказанный: '4.5' })],
      ['правильный дробный', сырая({ правильный: '9.5' })],
      ['каталог не строка', сырая({ каталог: '171' })],
      ['bbox короче четырёх', сырая({ bbox: '[0.1,0.2,0.3]' })],
      ['bbox не массив', сырая({ bbox: '0.1' })],
      ['bbox с нечислом', сырая({ bbox: '[0.1,0.2,0.3,"край"]' })],
    ]
    for (const [что, битая] of брак) {
      хранилище.записать('отзывы', документ(битая))
      expect(прочитатьОчередь(хранилище), что).toEqual([отзыв(1)])
    }
  })

  it('переросший документ подрезается на чтении', () => {
    const хранилище = new ХранилищеВПамяти()
    // Нормальным путём такого документа не бывает: единственный писатель ходит через
    // `добавитьОтзыв`. Но миграция, ручная правка или снижение потолка в будущей версии оставят
    // очередь длиннее предела, и без среза на чтении она пролежала бы так до следующей жалобы.
    const длинная = Array.from({ length: ПРЕДЕЛ_ОЧЕРЕДИ + 5 }, (_, номер) => отзыв(номер))
    хранилище.записать('отзывы', JSON.stringify(длинная))
    const прочитанная = прочитатьОчередь(хранилище)
    expect(прочитанная).toHaveLength(ПРЕДЕЛ_ОЧЕРЕДИ)
    // Голова, а не хвост: свежайшее первым — тот же порядок, каким его строит `добавитьОтзыв`.
    expect(прочитанная[0]!.время).toBe(0)
  })
})
