import { describe, expect, it } from 'vitest'
import { ХранилищеВПамяти } from './storage'
import {
  ПРЕДЕЛ_ОЧЕРЕДИ,
  добавитьОтзыв,
  записатьОтзыв,
  очиститьОчередь,
  прочитатьОчередь,
  type ЗаписьОтзыва,
} from './feedback'

const отзыв = (время: number): ЗаписьОтзыва => ({
  время,
  каталог: '1:abcdef012345:171',
  предсказанный: 4,
  правильный: 9,
  sim: 0.61,
  bbox: [0.1, 0.2, 0.3, 0.4],
})

describe('очередь отзывов', () => {
  it('при выключенном opt-in ничего не пишется', () => {
    const хранилище = new ХранилищеВПамяти()
    expect(записатьОтзыв(хранилище, отзыв(1), false)).toBe(false)
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })

  it('при включённом opt-in запись ложится и читается', () => {
    const хранилище = new ХранилищеВПамяти()
    expect(записатьОтзыв(хранилище, отзыв(1), true)).toBe(true)
    expect(прочитатьОчередь(хранилище)).toEqual([отзыв(1)])
  })

  it('digest каталога сохраняется в записи', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьОтзыв(хранилище, отзыв(1), true)
    expect(прочитатьОчередь(хранилище)[0]!.каталог).toBe('1:abcdef012345:171')
  })

  it('на пределе вытесняется самая старая', () => {
    let очередь: ЗаписьОтзыва[] = []
    for (let номер = 0; номер < ПРЕДЕЛ_ОЧЕРЕДИ + 1; номер++) {
      очередь = добавитьОтзыв(очередь, отзыв(номер))
    }
    expect(очередь).toHaveLength(ПРЕДЕЛ_ОЧЕРЕДИ)
    expect(очередь[очередь.length - 1]!.время).toBe(1)
  })

  it('очистка стирает всё', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьОтзыв(хранилище, отзыв(1), true)
    очиститьОчередь(хранилище)
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })

  it('мусор в хранилище даёт пустую очередь', () => {
    const хранилище = new ХранилищеВПамяти()
    // Сначала живая запись под тем же литеральным ключом: без неё промах по ключу выглядел бы
    // точно так же, как сработавшая валидация, — пустая очередь и зелёный тест при опечатке
    // в `КЛЮЧ`.
    хранилище.записать('отзывы', JSON.stringify([отзыв(1)]))
    expect(прочитатьОчередь(хранилище)).toEqual([отзыв(1)])
    хранилище.записать('отзывы', '{"не":"массив"}')
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })

  it('мутация пустой очереди не отравляет следующее чтение', () => {
    // `прочитатьJson` отдаёт четвёртый аргумент как есть, не проводя его через разбор, — и на
    // промахе по ключу, и на битом JSON. Общий массив на все вызовы копил бы чужие правки.
    const хранилище = new ХранилищеВПамяти()
    прочитатьОчередь(хранилище).push(отзыв(1))
    expect(прочитатьОчередь(хранилище)).toEqual([])
  })
})
