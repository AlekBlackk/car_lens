import { describe, expect, it } from 'vitest'
import { ХранилищеВПамяти } from './storage'
import {
  ПРЕДЕЛ_ИСТОРИИ,
  добавить,
  записатьИсторию,
  записьИзРешения,
  прочитатьИсторию,
  своя,
  type ЗаписьИстории,
} from './history'

const ЦИФРОВОЙ = '1:abcdef012345:171'

const запись = (время: number): ЗаписьИстории => ({
  время,
  каталог: ЦИФРОВОЙ,
  classIdx: 3,
  вид: 'модель',
  уверенность: 0.74,
  откалибровано: false,
})

describe('запись из решения', () => {
  it('модель превращается в запись', () => {
    const итог = записьИзРешения(
      { вид: 'модель', classIdx: 12, уверенность: 0.8, откалибровано: true },
      1000,
      ЦИФРОВОЙ,
    )
    expect(итог).toEqual({
      время: 1000,
      каталог: ЦИФРОВОЙ,
      classIdx: 12,
      вид: 'модель',
      уверенность: 0.8,
      откалибровано: true,
    })
  })

  it('бренд пишется без уверенности', () => {
    const итог = записьИзРешения({ вид: 'бренд', classIdx: 5 }, 2000, ЦИФРОВОЙ)
    expect(итог?.вид).toBe('бренд')
    expect(итог?.уверенность).toBeNull()
  })

  it('отказы и «определяю» историей не являются', () => {
    expect(записьИзРешения({ вид: 'определяю' }, 1, ЦИФРОВОЙ)).toBeNull()
    expect(записьИзРешения({ вид: 'ближе' }, 1, ЦИФРОВОЙ)).toBeNull()
    expect(записьИзРешения({ вид: 'неизвестно' }, 1, ЦИФРОВОЙ)).toBeNull()
  })
})

describe('кольцо истории', () => {
  it('свежие записи идут первыми', () => {
    const итог = добавить([запись(1)], запись(2))
    expect(итог[0]!.время).toBe(2)
    expect(итог[1]!.время).toBe(1)
  })

  it('обрезается ровно на пределе', () => {
    let история: ЗаписьИстории[] = []
    for (let номер = 0; номер < ПРЕДЕЛ_ИСТОРИИ + 10; номер++) {
      история = добавить(история, запись(номер))
    }
    expect(история).toHaveLength(ПРЕДЕЛ_ИСТОРИИ)
    expect(история[0]!.время).toBe(ПРЕДЕЛ_ИСТОРИИ + 9)
  })

  it('не меняет переданный массив', () => {
    const исходная = [запись(1)]
    добавить(исходная, запись(2))
    expect(исходная).toHaveLength(1)
  })
})

describe('версия каталога', () => {
  it('запись своего каталога признаётся своей', () => {
    expect(своя(запись(1), ЦИФРОВОЙ)).toBe(true)
  })

  it('запись чужого каталога — чужая', () => {
    expect(своя({ ...запись(1), каталог: '1:ffffffffffff:600' }, ЦИФРОВОЙ)).toBe(false)
  })
})

describe('хранилище истории', () => {
  it('записанное читается обратно', () => {
    const хранилище = new ХранилищеВПамяти()
    записатьИсторию(хранилище, [запись(7)])
    expect(прочитатьИсторию(хранилище)).toEqual([запись(7)])
  })

  it('мусор в хранилище даёт пустую историю', () => {
    const хранилище = new ХранилищеВПамяти()
    хранилище.записать('история', '[{"время":"вчера"}]')
    expect(прочитатьИсторию(хранилище)).toEqual([])
  })

  it('пустое хранилище даёт пустую историю', () => {
    expect(прочитатьИсторию(new ХранилищеВПамяти())).toEqual([])
  })
})
