import { записатьJson, прочитатьJson, type Хранилище } from './storage'

const КЛЮЧ = 'настройки'

/**
 * Потолок пользовательского порога. Не единица: порог 1.0 отключил бы подписи полностью,
 * и пользователь получил бы приложение, которое молчит всегда, без внятной причины.
 */
export const МАКСИМУМ_ПОРОГА = 0.9

export type Настройки = {
  порогУверенности: number
  показыватьТоп3: boolean
  сборОбратнойСвязи: boolean
}

export const НАСТРОЙКИ_ПО_УМОЛЧАНИЮ: Настройки = {
  порогУверенности: 0,
  показыватьТоп3: true,
  // §8 спеки: явный opt-in, выключен по умолчанию.
  сборОбратнойСвязи: false,
}

const булево = (значение: unknown, поумолчанию: boolean): boolean =>
  typeof значение === 'boolean' ? значение : поумолчанию

const порог = (значение: unknown): number => {
  if (typeof значение !== 'number' || !Number.isFinite(значение)) return 0
  if (значение < 0 || значение > МАКСИМУМ_ПОРОГА) return 0
  return значение
}

/**
 * Битые настройки откатываются к значениям по умолчанию, а не роняют запуск: в отличие от
 * ассетов §13.5, настройки описывают интерфейс, а не поведение распознавания.
 */
export function разобратьНастройки(сырое: unknown): Настройки {
  if (typeof сырое !== 'object' || сырое === null) return НАСТРОЙКИ_ПО_УМОЛЧАНИЮ
  const поля = сырое as Record<string, unknown>
  return {
    порогУверенности: порог(поля.порогУверенности),
    показыватьТоп3: булево(поля.показыватьТоп3, НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.показыватьТоп3),
    сборОбратнойСвязи: булево(поля.сборОбратнойСвязи, НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.сборОбратнойСвязи),
  }
}

export function прочитатьНастройки(хранилище: Хранилище): Настройки {
  return прочитатьJson(хранилище, КЛЮЧ, разобратьНастройки, НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
}

export function записатьНастройки(хранилище: Хранилище, настройки: Настройки): void {
  записатьJson(хранилище, КЛЮЧ, настройки)
}
