import { decisionKey, type Решение } from './decide'
import type { ПодписьТрека, СобытиеКлассификации } from './pipeline'
import type { Match } from './plugins'
import { confidenceFromSim, type Калибровка, type Пороги } from './thresholds'

/**
 * Пользовательский порог поверх решения §6.4. Не подменяет `simMin` из ассета намеренно:
 * `sim` — косинус до центроида, шкала нечитаемая человеку, а подобранное по §13.5
 * значение молча потерялось бы вместе со связью между негативами и телефоном. Обратная
 * сторона сделки: порог хранится в шкале уверенности, поэтому после перекалибровки те же
 * сохранённые 0.5 отрежут на другом `sim`, и пользователю об этом никто не скажет.
 *
 * `порог` — в той же шкале, что и `решение.уверенность`: выход `confidenceFromSim`, то
 * есть `[0, 1]`; приходит из `порогУверенности` в `store/settings.ts`, где значение вне
 * допустимого диапазона не подтягивается к потолку, а отбрасывается в 0.
 *
 * Ползунок умеет только ужесточать: при пороге 0 поведение ровно то, что задаёт §6.4.
 */
export function применитьПорог(решение: Решение, порог: number): Решение {
  if (решение.kind !== 'модель') return решение
  if (решение.confidence >= порог) return решение
  return { kind: 'неизвестно' }
}

/**
 * Тот же порог, но над всем списком подписей кадра. Живёт здесь, а не на экране, чтобы
 * подмену решения можно было проверить тестом: спред `{ ...подпись, decision: решение }`
 * TypeScript не стережёт — опечатка в имени поля создаёт лишнее поле вместо ошибки типа,
 * и подпись уезжает на экран с непогашенным решением.
 *
 * Подписи, которых порог не коснулся, возвращаются той же ссылкой: копия на каждый кадр
 * ради неизменившегося значения — мусор на горячем пути.
 */
export function подписиСПорогом(подписи: ПодписьТрека[], порог: number): ПодписьТрека[] {
  return подписи.map((подпись) => {
    const решение = применитьПорог(подпись.decision, порог)
    return решение === подпись.decision ? подпись : { ...подпись, decision: решение }
  })
}

/**
 * Отличает «подпись погашена вашим ползунком» от «подпись отвергнута порогами отказа §6.4».
 * Снаружи оба выглядят одинаково — `{ вид: 'неизвестно' }`, — а объяснить пользователю их
 * надо по-разному: первое чинится ползунком, второе не чинится ничем.
 *
 * Живёт здесь, а не на экране «Детали», по той же причине, по которой там не живёт
 * `применитьПорог`: это арифметика над порогом, и её надо уметь проверять без React.
 *
 * `sim < пороги.simMin` отсекается до сравнения с порогом намеренно: такую гипотезу §6.4
 * отверг сам, ползунок к ней отношения не имеет, и обещать пользователю, что её вернёт
 * сдвиг ползунка, было бы враньём.
 */
export function скрытоПорогом(
  решение: Решение,
  топ1: Match | null,
  порог: number,
  пороги: Пороги,
  калибровка: Калибровка,
): boolean {
  if (порог <= 0) return false
  if (решение.kind !== 'неизвестно') return false
  if (топ1 === null || топ1.sim < пороги.simMin) return false
  return confidenceFromSim(топ1.sim, калибровка) < порог
}

/**
 * Перекладывает ключ `decision_churn` с сырого решения §6.4 на то, которое видит
 * пользователь. Закрывает долг вехи M-1.6: `pipeline.ts` проставляет `ключРешения` из
 * `decide()`, а пользовательский порог применяется позже, на JS-стороне, — счётчик мерил
 * устойчивость подписи, которой на экране могло не быть.
 *
 * Разница не косметическая. При поднятом ползунке подряд идущие «модель:3» и «модель:4»
 * гасятся в одно и то же «неизвестно», и сырой счётчик засчитывал бы смену там, где
 * пользователь смены не видел, — то есть завышал `decision_churn` тем сильнее, чем выше
 * задран порог.
 *
 * `подписи` ожидаются уже пропущенными через `применитьПорог`: единственный вызов порога
 * живёт в `CameraScreen`, и второй здесь означал бы два места, где решается одно и то же.
 *
 * Событие трека, для которого подписи не нашлось, возвращается той же ссылкой. Такого
 * быть не должно — события рождаются только у живых треков, — но выдумывать ключ вместо
 * отсутствующего значило бы подмешать в замер число, которого никто не наблюдал.
 */
export function ключиВидимыхРешений(
  события: СобытиеКлассификации[],
  подписи: ПодписьТрека[],
): СобытиеКлассификации[] {
  return события.map((событие) => {
    const подпись = подписи.find((кандидат) => кандидат.id === событие.id)
    if (подпись === undefined) return событие
    const ключ = decisionKey(подпись.decision)
    return ключ === событие.decisionKey ? событие : { ...событие, decisionKey: ключ }
  })
}
