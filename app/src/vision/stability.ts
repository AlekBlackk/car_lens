/**
 * Приёмочный замер второй половины M-1.6: насколько EMA успокаивает подпись.
 *
 * Две разные величины, и смешивать их нельзя:
 *
 * - `top1_churn` — смена сырого топ-1. Два ряда, мгновенный и по EMA, снятые в одном
 *   прогоне на одних и тех же кадрах: два раздельных замера сравнивали бы заодно
 *   освещение, ракурс и хват телефона.
 * - `decision_churn` — смена того, что видит пользователь, включая переходы
 *   «определяю» → «модель» → «неизвестно». Считается только по EMA: мгновенного решения
 *   не существует. Ключ приходит уже после пользовательского порога §7 — накопитель
 *   кормится тем, что уехало на экран, а не сырым выводом `decide()`.
 *
 * Замер меряет устойчивость, а не правильность. Трекер, упорно называющий любую машину
 * одним классом, покажет идеальный ноль. На весах M-1 из Stanford Cars правильность и не
 * проверяема: веса расходные (§10), street_holdout появится на M1.
 *
 * Живёт на JS-стороне: копит массивы произвольной длины, чего SharedValue не умеет.
 */
import type { СобытиеКлассификации } from './pipeline'

/** ~30 секунд наблюдения одной машины при 8 Гц. Считается по наблюдениям, а не по секундам:
 *  при просадке до 5 Гц по §6.5 «30 секунд» дали бы вдвое меньше точек. */
export const РАЗМЕР_ВЫБОРКИ = 240

export type Сводка = {
  наблюдений: number
  треков: number
  top1МгновенныйСмен: number
  top1EmaСмен: number
  решенийСмен: number
  классовМгновенный: number
  классовEma: number
  видов: number
}

/**
 * Знаменатель — число переходов, а не наблюдений: первое наблюдение каждого трека сменой
 * быть не может, и считать его в знаменателе значило бы занижать долю тем сильнее, чем
 * больше треков прошло через кадр.
 */
const доля = (смен: number, наблюдений: number, треков: number): string => {
  const переходов = наблюдений - треков
  return переходов > 0 ? (смен / переходов).toFixed(3) : '0.000'
}

export class StabilityCollector {
  private наблюдений = 0
  private top1МгновенныйСмен = 0
  private top1EmaСмен = 0
  private решенийСмен = 0
  private напечатано = false
  private предыдущие: Record<number, { мгновенный: number; ema: number; ключ: string }> = {}
  private классыМгновенный: Record<number, true> = {}
  private классыEma: Record<number, true> = {}
  private видыРешений: Record<string, true> = {}
  private треки: Record<number, true> = {}

  добавить(события: СобытиеКлассификации[]): void {
    if (this.напечатано) return
    for (const событие of события) {
      const прошлое = this.предыдущие[событие.id]
      if (прошлое != null) {
        if (прошлое.мгновенный !== событие.top1Мгновенный) this.top1МгновенныйСмен++
        if (прошлое.ema !== событие.top1Ema) this.top1EmaСмен++
        if (прошлое.ключ !== событие.ключРешения) this.решенийСмен++
      }
      this.предыдущие[событие.id] = {
        мгновенный: событие.top1Мгновенный,
        ema: событие.top1Ema,
        ключ: событие.ключРешения,
      }
      this.классыМгновенный[событие.top1Мгновенный] = true
      this.классыEma[событие.top1Ema] = true
      this.видыРешений[событие.ключРешения] = true
      this.треки[событие.id] = true
      this.наблюдений++
      if (this.наблюдений >= РАЗМЕР_ВЫБОРКИ) {
        this.напечатать()
        return
      }
    }
  }

  сводка(): Сводка {
    return {
      наблюдений: this.наблюдений,
      треков: Object.keys(this.треки).length,
      top1МгновенныйСмен: this.top1МгновенныйСмен,
      top1EmaСмен: this.top1EmaСмен,
      решенийСмен: this.решенийСмен,
      классовМгновенный: Object.keys(this.классыМгновенный).length,
      классовEma: Object.keys(this.классыEma).length,
      видов: Object.keys(this.видыРешений).length,
    }
  }

  private напечатать(): void {
    this.напечатано = true
    const с = this.сводка()
    // Единственный канал снятия чисел с устройства, как и у НакопительЦеныМоста:
    // `adb logcat -d -s ReactNativeJS:I | grep СТАБИЛЬНОСТЬ`.
    // eslint-disable-next-line no-console
    console.log(
      `СТАБИЛЬНОСТЬ top1_churn мгновенный=${с.top1МгновенныйСмен}/${с.наблюдений} ` +
        `(${доля(с.top1МгновенныйСмен, с.наблюдений, с.треков)}) классов=${с.классовМгновенный} ` +
        `ema=${с.top1EmaСмен}/${с.наблюдений} (${доля(с.top1EmaСмен, с.наблюдений, с.треков)}) ` +
        `классов=${с.классовEma} треков=${с.треков}`,
    )
    // eslint-disable-next-line no-console
    console.log(
      `СТАБИЛЬНОСТЬ decision_churn ema=${с.решенийСмен}/${с.наблюдений} ` +
        `(${доля(с.решенийСмен, с.наблюдений, с.треков)}) видов=${с.видов} треков=${с.треков}`,
    )
  }
}
