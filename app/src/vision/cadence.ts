/**
 * Каденция конвейера, подстроенная под цену его шага.
 *
 * Фиксированных 100 мс (`PIPELINE_INTERVAL_MS` в `CameraScreen.tsx`) хватает, пока шаг дешёвый:
 * полный шаг — детектор плюс классификатор на GPU — стоит около 51 мс (`bench/gpu-classifier-
 * preregistration.md`), то есть устройство занято чуть больше половины времени. Но цена шага
 * не постоянна: на горячем корпусе тот же код считается втрое дольше (104 против 300 мс,
 * `bench/latency.md`). Шаг дороже интервала означает, что конвейер идёт спина к спине — GPU и
 * ядра заняты почти полностью, корпус греется ещё сильнее, шаг дорожает дальше, и приложение
 * само загоняет себя в 2-3 кадра в секунду.
 *
 * Регулятор разрывает эту петлю: интервал до следующего шага не меньше `цена / MAX_DUTY`, то
 * есть устройство занято конвейером не больше `MAX_DUTY` времени, как бы дорого шаг ни
 * обходился. Пока шаг дешевле `MAX_DUTY × 100 мс`, интервал остаётся базовым и поведение
 * прежнее.
 *
 * Имена латиницей: константы захватываются воркетом (см. `workletClosure.test.ts`).
 */

/**
 * Доля времени, которую конвейеру разрешено занимать устройство. 0.6 — это нынешняя нагрузка
 * здорового состояния (полный шаг ≈ 51-57 мс из 100): регулятор не добавляет ограничений
 * там, где всё в порядке, и вступает в дело только когда шаг заметно дороже обычного.
 */
export const MAX_DUTY = 0.6

/**
 * Потолок интервала. Без него один аномальный шаг (первый кадр, где грузятся модели и
 * собирается GPU-делегат, стоит секунды) отключил бы узнавание на десяток секунд.
 */
export const MAX_INTERVAL_MS = 1000

/** Интервал до следующего шага конвейера по цене только что завершённого, миллисекунды. */
export function nextPipelineInterval(stepCostMs: number, baseIntervalMs: number): number {
  'worklet'
  return Math.min(MAX_INTERVAL_MS, Math.max(baseIntervalMs, stepCostMs / MAX_DUTY))
}
