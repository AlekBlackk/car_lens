/**
 * Темпоральная агрегация §6.3: EMA по L2-нормализованному эмбеддингу с ренормализацией
 * после каждого шага.
 *
 * Не по softmax-вероятностям: усреднение логитов даёт хуже, потому что одиночные плохие
 * ракурсы дают уверенно неправильный пик, а в пространстве эмбеддингов они просто уводят
 * точку в разреженную область, откуда kNN не даст высокого сходства.
 *
 * Вход от моста считается недоверенным. `NaN` в векторе, пришедший из повреждённого
 * буфера, молча проехал бы через kNN и вылез подписью — поэтому такой шаг отвергается
 * явно, а трек не засчитывает его наблюдением.
 */

/** `ALPHA` из §6.2 спеки. */
export const EMA_ALPHA = 0.35

/**
 * Ниже этого модуля направление вектора не определено.
 *
 * Имя латиницей — не стиль, а требование `__closure`: константа модуля захватывается
 * воркетом, а ключи с не-ASCII символами не доезжают до worklet-рантайма и приезжают
 * `undefined`. Сравнение с `undefined` даёт `false`, и отказ на нулевой норме отключился бы
 * молча. Сторожит `workletClosure.test.ts`.
 */
const MIN_NORM = 1e-6

export class DimensionError extends Error {
  constructor(сообщение: string) {
    super(сообщение)
    this.name = 'DimensionError'
  }
}

/**
 * `принят: false` — шаг отвергнут: вектор остался прежним, и наблюдение засчитывать
 * нельзя. Иначе испорченные кадры протолкнули бы трек через `min_observations` без
 * единого настоящего измерения.
 */
export type ИтогEMA = { вектор: number[] | null; принят: boolean }

export function emaStep(предыдущий: number[] | null, новый: Float32Array, alpha: number): ИтогEMA {
  'worklet'
  const длина = новый.length
  if (предыдущий != null && предыдущий.length !== длина) {
    throw new DimensionError(
      `эмбеддинг: ${длина} чисел против ${предыдущий.length}, запомненных треком`,
    )
  }
  let сумма = 0
  for (let номер = 0; номер < длина; номер++) {
    const число = новый[номер]!
    if (!Number.isFinite(число)) {
      return { вектор: предыдущий, принят: false }
    }
    сумма += число * число
  }
  const норма = Math.sqrt(сумма)
  if (норма < MIN_NORM) {
    return { вектор: предыдущий, принят: false }
  }
  const нормализованный: number[] = new Array(длина)
  for (let номер = 0; номер < длина; номер++) {
    нормализованный[номер] = новый[номер]! / норма
  }
  // Инициализация первым эмбеддингом, а не нулевым вектором: точка, ползущая из начала
  // координат, давала бы заведомо плохой kNN ровно в тот момент, когда счётчик
  // наблюдений перешагивает `min_observations`.
  if (предыдущий == null) {
    return { вектор: нормализованный, принят: true }
  }
  const смешанный: number[] = new Array(длина)
  let суммаСмеси = 0
  for (let номер = 0; номер < длина; номер++) {
    const старое = предыдущий[номер]!
    const число = старое + alpha * (нормализованный[номер]! - старое)
    смешанный[номер] = число
    суммаСмеси += число * число
  }
  const нормаСмеси = Math.sqrt(суммаСмеси)
  // Вырожденный случай: старое и новое почти противоположны, и смесь схлопнулась в ноль.
  // Предпочесть свежее наблюдение честнее, чем вернуть шум от деления на почти ноль.
  if (нормаСмеси < MIN_NORM) {
    return { вектор: нормализованный, принят: true }
  }
  for (let номер = 0; номер < длина; номер++) {
    смешанный[номер] = смешанный[номер]! / нормаСмеси
  }
  return { вектор: смешанный, принят: true }
}
