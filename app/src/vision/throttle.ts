/**
 * Отбор кропов для классификации, §6.2: не чаще 8 Гц **на трек**, не больше `MAX_CROPS`
 * кропов за кадр, мелкие боксы пропускаются.
 *
 * Троттлинг по треку, а не по кадру: две машины в кадре обязаны считаться обе, а одна
 * машина не должна съедать бюджет соседней. До появления трекера здесь стоял счёт по
 * кадру — временная форма, которой это и было.
 *
 * Часы — `nowMs`, монотонный timestamp кадра. `Date.now()` здесь не используется: смерть
 * трека и троттлинг обязаны мерить одной линейкой, иначе прыжок стенных часов (NTP, смена
 * зоны) разом убьёт половину треков и оставит вторую половину бессмертной.
 */
import type { Box } from './plugins'

/** §6.2: ≤8 Гц на трек. */
export const CLASSIFY_INTERVAL_MS = 125

/**
 * Сколько кропов классифицируется за один кадр.
 *
 * Один, а не два, как написано в §6.2 спеки, и это осознанное отступление от неё, а не
 * недосмотр. Классификация стоит 47 мс на кроп (`bench/latency.md`), детекция — ещё 38,
 * и кадр с двумя кропами обходился в 132 мс против 85 у кадра с одним. Пользователю
 * видна не средняя цена кадра, а разброс: кадры прыгали вдвое по длительности в
 * зависимости от того, сколько машин попало в кадр, и выглядело это рывками превью, а не
 * «иногда чуть медленнее».
 *
 * Двум машинам в кадре это стоит очерёдности: каждая классифицируется через кадр, то
 * есть вдвое реже одиночной. Порог 8 Гц на трек (`CLASSIFY_INTERVAL_MS`) при каденции
 * конвейера 10 Гц (`PIPELINE_INTERVAL_MS` в `CameraScreen.tsx`) всё равно пропускает трек
 * к классификации через кадр, поэтому одиночная машина от этой правки не теряет ничего.
 *
 * Слотов в мосту по-прежнему два (`МАКСИМУМ_КРОПОВ` в `CarVisionEmbedPlugin.kt`), и
 * опускать их следом нельзя: самопроверка контракта слотов §4.8 (`slotContract.ts`)
 * шлёт намеренно два бокса — иначе проверить, что два результата одного вызова лежат в
 * независимой памяти, нечем.
 */
export const MAX_CROPS = 1

/**
 * Поля ASCII не по своей нужде, а по совместимости: сюда передаются `Трек` из
 * `pipeline.ts`, а те лежат в `SharedValue` и потому обязаны быть ASCII (см. KDoc `Трек`).
 * Структурная типизация требует, чтобы имена совпадали.
 */
export type КандидатТрек = { id: number; box: Box; classifiedAt: number }

export function pickForClassify(
  треки: КандидатТрек[],
  nowMs: number,
  minShortSidePx: number,
): { id: number; box: Box }[] {
  'worklet'
  const годные: КандидатТрек[] = []
  for (let номер = 0; номер < треки.length; номер++) {
    const трек = треки[номер]!
    if (nowMs - трек.classifiedAt < CLASSIFY_INTERVAL_MS) continue
    const короткаяСторона = Math.min(трек.box.w, трек.box.h)
    if (короткаяСторона < minShortSidePx) continue
    годные.push(трек)
  }
  годные.sort((первый, второй) => {
    const разница = второй.box.conf - первый.box.conf
    if (разница !== 0) return разница
    return первый.id - второй.id
  })
  const сколько = Math.min(MAX_CROPS, годные.length)
  const выбранные: { id: number; box: Box }[] = new Array(сколько)
  for (let номер = 0; номер < сколько; номер++) {
    выбранные[номер] = { id: годные[номер]!.id, box: годные[номер]!.box }
  }
  return выбранные
}
