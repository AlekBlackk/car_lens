import { describe, expect, it } from 'vitest'
import { применитьПорог, скрытоПорогом } from './userThreshold'
import type { Решение } from './decide'
import { parseCalibration, parseThresholds } from './thresholds'

const модель = (уверенность: number): Решение => ({
  вид: 'модель',
  classIdx: 3,
  уверенность,
  откалибровано: false,
})

describe('пользовательский порог', () => {
  it('порог 0 не меняет ничего', () => {
    const решение = модель(0.01)
    expect(применитьПорог(решение, 0)).toBe(решение)
  })

  it('модель ниже порога становится «неизвестно»', () => {
    expect(применитьПорог(модель(0.4), 0.5)).toEqual({ вид: 'неизвестно' })
  })

  it('модель ровно на пороге проходит', () => {
    expect(применитьПорог(модель(0.5), 0.5).вид).toBe('модель')
  })

  it('модель заметно выше порога проходит нетронутой', () => {
    const решение = модель(0.8)
    expect(применитьПорог(решение, 0.5)).toBe(решение)
  })

  it('бренд, «определяю» и отказы проходят насквозь при любом пороге', () => {
    const прочие: Решение[] = [
      { вид: 'бренд', classIdx: 2 },
      { вид: 'определяю' },
      { вид: 'ближе' },
      { вид: 'неизвестно' },
    ]
    for (const решение of прочие) {
      expect(применитьПорог(решение, 0.9)).toBe(решение)
    }
  })
})

const пороги = parseThresholds({
  version: 1,
  tuned: false,
  sim_min: 0.42,
  margin_min: 0.05,
  min_observations: 3,
  min_short_side_px: 120,
})

const калибровка = parseCalibration({
  version: 1,
  method: 'isotonic_piecewise_linear',
  tuned: false,
  knots: [
    [0.4, 0.05],
    [1.0, 0.98],
  ],
  clip: [0.01, 0.98],
})

describe('подпись скрыта пользовательским порогом', () => {
  // sim 0.9 на этой таблице даёт примерно 0.82 уверенности: выше 0.5 и ниже 0.9.
  const внятная = { classIdx: 7, sim: 0.9 }

  it('«неизвестно» поверх внятной гипотезы при высоком пороге — это порог', () => {
    expect(скрытоПорогом({ вид: 'неизвестно' }, внятная, 0.9, пороги, калибровка)).toBe(true)
  })

  it('тот же случай при пороге ниже уверенности — не порог', () => {
    expect(скрытоПорогом({ вид: 'неизвестно' }, внятная, 0.5, пороги, калибровка)).toBe(false)
  })

  it('порог 0 не скрывает ничего', () => {
    expect(скрытоПорогом({ вид: 'неизвестно' }, внятная, 0, пороги, калибровка)).toBe(false)
  })

  it('гипотеза ниже simMin отвергнута §6.4, а не порогом', () => {
    const слабая = { classIdx: 7, sim: 0.3 }
    expect(скрытоПорогом({ вид: 'неизвестно' }, слабая, 0.9, пороги, калибровка)).toBe(false)
  })

  it('без гипотез скрывать нечего', () => {
    expect(скрытоПорогом({ вид: 'неизвестно' }, null, 0.9, пороги, калибровка)).toBe(false)
  })

  it('решения, кроме «неизвестно», порогом не скрыты — их видно', () => {
    const прочие: Решение[] = [
      { вид: 'модель', classIdx: 7, уверенность: 0.82, откалибровано: false },
      { вид: 'бренд', classIdx: 7 },
      { вид: 'определяю' },
      { вид: 'ближе' },
    ]
    for (const решение of прочие) {
      expect(скрытоПорогом(решение, внятная, 0.9, пороги, калибровка)).toBe(false)
    }
  })
})
