import { describe, expect, test } from 'vitest'
import type { Box } from './plugins'
import { CONF_HIGH, IOU_MIN, LOST_MAX_MS, MAX_TRACKS, iou, updateTracks } from './tracker'

const бокс = (x: number, y: number, conf = 0.9, w = 100, h = 100): Box => ({ x, y, w, h, conf })
const трек = (id: number, б: Box, виденВ = 0) => ({ id, бокс: б, виденВ })

describe('iou', () => {
  test('совпадающие боксы дают единицу', () => {
    expect(iou(бокс(0, 0), бокс(0, 0))).toBeCloseTo(1, 6)
  })

  test('непересекающиеся дают ноль', () => {
    expect(iou(бокс(0, 0), бокс(500, 500))).toBe(0)
  })

  test('касающиеся краями дают ноль, а не отрицательное', () => {
    expect(iou(бокс(0, 0), бокс(100, 0))).toBe(0)
  })

  test('половинное перекрытие даёт треть', () => {
    expect(iou(бокс(0, 0), бокс(50, 0))).toBeCloseTo(1 / 3, 6)
  })
})

describe('updateTracks', () => {
  test('машина едет поперёк кадра — id сохраняется', () => {
    let треки = [трек(1, бокс(0, 0))]
    let следующий = 2
    for (let шаг = 1; шаг <= 5; шаг++) {
      const итог = updateTracks(треки, [бокс(шаг * 20, 0)], шаг * 33, следующий)
      expect(итог.сопоставленные).toHaveLength(1)
      expect(итог.сопоставленные[0]!.id).toBe(1)
      expect(итог.рождённые).toHaveLength(0)
      треки = [трек(1, итог.сопоставленные[0]!.бокс, шаг * 33)]
      следующий = итог.следующийId
    }
  })

  test('перекрытие ниже IOU_MIN не сопоставляется, а рождает новый трек', () => {
    const итог = updateTracks([трек(1, бокс(0, 0))], [бокс(85, 0)], 10, 2)
    expect(iou(бокс(0, 0), бокс(85, 0))).toBeLessThan(IOU_MIN)
    expect(итог.сопоставленные).toHaveLength(0)
    expect(итог.рождённые).toEqual([{ id: 2, бокс: бокс(85, 0) }])
  })

  test('слабый бокс продолжает осиротевший трек', () => {
    const слабый = бокс(10, 0, CONF_HIGH - 0.05)
    const итог = updateTracks([трек(1, бокс(0, 0))], [слабый], 10, 2)
    expect(итог.сопоставленные).toEqual([{ id: 1, бокс: слабый }])
    expect(итог.рождённые).toHaveLength(0)
  })

  test('слабый бокс без трека нового трека не рождает', () => {
    const итог = updateTracks([], [бокс(0, 0, CONF_HIGH - 0.05)], 10, 1)
    expect(итог.рождённые).toHaveLength(0)
    expect(итог.следующийId).toBe(1)
  })

  test('уверенный бокс перед слабым: первая стадия забирает трек', () => {
    const уверенный = бокс(5, 0, 0.95)
    const слабый = бокс(10, 0, 0.4)
    const итог = updateTracks([трек(1, бокс(0, 0))], [слабый, уверенный], 10, 2)
    expect(итог.сопоставленные).toEqual([{ id: 1, бокс: уверенный }])
  })

  test('трек жив ровно на границе LOST_MAX_MS', () => {
    const итог = updateTracks([трек(1, бокс(0, 0), 0)], [], LOST_MAX_MS, 2)
    expect(итог.умершие).toEqual([])
  })

  test('трек мёртв на миллисекунду позже границы', () => {
    const итог = updateTracks([трек(1, бокс(0, 0), 0)], [], LOST_MAX_MS + 1, 2)
    expect(итог.умершие).toEqual([1])
  })

  test('сопоставленный трек не умирает, даже если давно не виден', () => {
    const итог = updateTracks([трек(1, бокс(0, 0), 0)], [бокс(0, 0)], LOST_MAX_MS + 100, 2)
    expect(итог.умершие).toEqual([])
    expect(итог.сопоставленные).toHaveLength(1)
  })

  test('живой трек не вытесняется рождением при полном MAX_TRACKS', () => {
    const треки = [
      трек(1, бокс(0, 0)),
      трек(2, бокс(200, 0)),
      трек(3, бокс(400, 0)),
      трек(4, бокс(600, 0)),
    ]
    const итог = updateTracks(треки, [бокс(0, 0), бокс(800, 0, 0.99)], 10, 5)
    expect(итог.сопоставленные).toHaveLength(1)
    expect(итог.умершие).toHaveLength(0)
    expect(итог.рождённые).toHaveLength(0)
  })

  test('место освобождается смертью трека и достаётся сильнейшему кандидату', () => {
    const треки = [
      трек(1, бокс(0, 0), 0),
      трек(2, бокс(200, 0), 0),
      трек(3, бокс(400, 0), 0),
      трек(4, бокс(600, 0), 0),
    ]
    const итог = updateTracks(треки, [бокс(800, 0, 0.7), бокс(1000, 0, 0.95)], LOST_MAX_MS + 1, 5)
    expect(итог.умершие).toEqual([1, 2, 3, 4])
    expect(итог.рождённые).toHaveLength(Math.min(2, MAX_TRACKS))
    expect(итог.рождённые[0]!.бокс.conf).toBe(0.95)
  })

  test('два трека претендуют на один бокс — забирает тот, у кого IoU больше', () => {
    const итог = updateTracks([трек(1, бокс(0, 0)), трек(2, бокс(30, 0))], [бокс(35, 0)], 10, 3)
    expect(итог.сопоставленные).toEqual([{ id: 2, бокс: бокс(35, 0) }])
  })

  test('пересечение с неамбигуозной матрицей сохраняет личности', () => {
    const итог = updateTracks(
      [трек(1, бокс(0, 0)), трек(2, бокс(120, 0))],
      [бокс(10, 0), бокс(130, 0)],
      10,
      3,
    )
    const поId = итог.сопоставленные.slice().sort((а, б) => а.id - б.id)
    expect(поId[0]!.бокс.x).toBe(10)
    expect(поId[1]!.бокс.x).toBe(130)
  })

  test('полное совпадение боксов даёт детерминированный, пусть и произвольный, исход', () => {
    const вход = () =>
      updateTracks([трек(2, бокс(0, 0)), трек(1, бокс(0, 0))], [бокс(0, 0), бокс(0, 0)], 10, 3)
    expect(вход().сопоставленные).toEqual(вход().сопоставленные)
    // Личность здесь не гарантируется: IoU-only трекер без motion- и appearance-модели
    // не знает, какая из двух машин какая. Гарантируется только повторяемость.
    expect(вход().сопоставленные[0]!.id).toBe(1)
  })

  test('вход не мутируется', () => {
    const исходный = бокс(0, 0)
    const треки = [трек(1, исходный, 0)]
    updateTracks(треки, [бокс(500, 0)], LOST_MAX_MS + 1, 2)
    expect(треки).toHaveLength(1)
    expect(треки[0]!.бокс).toBe(исходный)
  })
})
