/**
 * ByteTrack-lite: сопоставление боксов между кадрами (§13.3 кладёт трекинг в JS-воркет).
 *
 * От оригинала взята главная идея — две стадии ассоциации по уверенности, — но без
 * Kalman-фильтра и без венгерского алгоритма. На ≤4 треках и ≤4 боксах жадный проход по
 * убыванию IoU даёт то же паросочетание почти всегда, а когда расходится — расходится на
 * один кадр. Это не недосмотр: 300 строк линейной алгебры ради четырёх боксов стоили бы
 * дороже, чем весь выигрыш.
 *
 * Известное ограничение: при полном перекрытии боксов личность машины не сохраняется.
 * IoU-only трекер без motion- и appearance-модели знать её не может; гарантируется только
 * детерминированность исхода.
 *
 * Модуль ничего не знает об эмбеддингах: он отвечает на вопрос «кому какой бокс достался»,
 * а состояние трека держит `pipeline.ts`.
 */
import type { Box } from './plugins'

/** Ниже этого IoU пара не считается сопоставлением. */
export const IOU_MIN = 0.3

/** Граница между корзинами ByteTrack. Нижняя корзина начинается с порога детектора (0.35). */
export const CONF_HIGH = 0.5

/**
 * Сколько трек живёт без попаданий. В миллисекундах, а не в кадрах: частота падает до
 * 5 Гц по §6.5, и «десять кадров» означало бы то полсекунды, то две.
 */
export const LOST_MAX_MS = 500

/** `MAX_TRACKS_DRAWN` из §6.2. */
export const MAX_TRACKS = 4

// Все четыре константы подобраны рассуждением, а не замером на данных. Тот же смысл, что
// у флага `tuned: false` в `thresholds.json`, только в коде: пересматриваются на M5, когда
// появится street_holdout.

export type ТрекГеометрия = { id: number; бокс: Box; виденВ: number }

export type ИтогТрекера = {
  сопоставленные: { id: number; бокс: Box }[]
  умершие: number[]
  рождённые: { id: number; бокс: Box }[]
  следующийId: number
}

export function iou(первый: Box, второй: Box): number {
  'worklet'
  const левый = Math.max(первый.x, второй.x)
  const верхний = Math.max(первый.y, второй.y)
  const правый = Math.min(первый.x + первый.w, второй.x + второй.w)
  const нижний = Math.min(первый.y + первый.h, второй.y + второй.h)
  const ширина = правый - левый
  const высота = нижний - верхний
  if (ширина <= 0 || высота <= 0) return 0
  const пересечение = ширина * высота
  const объединение = первый.w * первый.h + второй.w * второй.h - пересечение
  if (объединение <= 0) return 0
  return пересечение / объединение
}

export function updateTracks(
  треки: ТрекГеометрия[],
  боксы: Box[],
  nowMs: number,
  следующийId: number,
): ИтогТрекера {
  'worklet'
  const трекЗанят: boolean[] = new Array(треки.length)
  const боксЗанят: boolean[] = new Array(боксы.length)
  for (let номер = 0; номер < треки.length; номер++) трекЗанят[номер] = false
  for (let номер = 0; номер < боксы.length; номер++) боксЗанят[номер] = false

  const сопоставленные: { id: number; бокс: Box }[] = []

  // Одна стадия ассоциации: пары считаются, сортируются по полному ключу и разбираются
  // сверху. Ключ полный намеренно — опора на стабильность сортировки движка означала бы,
  // что один и тот же кадр может дать разное назначение id.
  const стадия = (индексыБоксов: number[]): void => {
    const пары: { значение: number; трек: number; бокс: number; id: number }[] = []
    for (let к = 0; к < индексыБоксов.length; к++) {
      const бИндекс = индексыБоксов[к]!
      if (боксЗанят[бИндекс]!) continue
      for (let т = 0; т < треки.length; т++) {
        if (трекЗанят[т]!) continue
        const значение = iou(треки[т]!.бокс, боксы[бИндекс]!)
        if (значение < IOU_MIN) continue
        пары.push({ значение, трек: т, бокс: бИндекс, id: треки[т]!.id })
      }
    }
    пары.sort((первая, вторая) => {
      if (вторая.значение !== первая.значение) return вторая.значение - первая.значение
      if (первая.id !== вторая.id) return первая.id - вторая.id
      return первая.бокс - вторая.бокс
    })
    for (let к = 0; к < пары.length; к++) {
      const пара = пары[к]!
      if (трекЗанят[пара.трек]! || боксЗанят[пара.бокс]!) continue
      трекЗанят[пара.трек] = true
      боксЗанят[пара.бокс] = true
      сопоставленные.push({ id: пара.id, бокс: боксы[пара.бокс]! })
    }
  }

  const уверенные: number[] = []
  const слабые: number[] = []
  for (let номер = 0; номер < боксы.length; номер++) {
    if (боксы[номер]!.conf >= CONF_HIGH) уверенные.push(номер)
    else слабые.push(номер)
  }
  стадия(уверенные)
  стадия(слабые)

  const умершие: number[] = []
  let живых = 0
  for (let номер = 0; номер < треки.length; номер++) {
    if (трекЗанят[номер]!) {
      живых++
      continue
    }
    if (nowMs - треки[номер]!.виденВ > LOST_MAX_MS) умершие.push(треки[номер]!.id)
    else живых++
  }

  // Порядок «сопоставили — убрали мёртвые — посчитали места — родили» выбран так, что
  // живой трек не может быть вытеснен рождением вообще.
  const мест = MAX_TRACKS - живых
  const рождённые: { id: number; бокс: Box }[] = []
  let свободныйId = следующийId
  if (мест > 0) {
    const кандидаты: number[] = []
    for (let к = 0; к < уверенные.length; к++) {
      const индекс = уверенные[к]!
      if (!боксЗанят[индекс]!) кандидаты.push(индекс)
    }
    кандидаты.sort((первый, второй) => {
      const разница = боксы[второй]!.conf - боксы[первый]!.conf
      if (разница !== 0) return разница
      return первый - второй
    })
    const сколько = Math.min(мест, кандидаты.length)
    for (let к = 0; к < сколько; к++) {
      рождённые.push({ id: свободныйId, бокс: боксы[кандидаты[к]!]! })
      свободныйId++
    }
  }

  return { сопоставленные, умершие, рождённые, следующийId: свободныйId }
}
