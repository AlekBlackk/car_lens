/**
 * Корень приложения: открывает хранилище, держит состояние, переживающее экраны, и водит
 * по четырём экранам §6.6.
 *
 * Порядок здесь — часть поведения, а не стиль. Хранилище открывается до камеры: первый же
 * распознанный трек пишется в историю, и если истории ещё нет, запись теряется молча.
 * Поэтому до готовности хранилища камера не монтируется вовсе, а пользователь видит, чего
 * приложение ждёт.
 *
 * Камера, наоборот, не размонтируется никогда: в ней живут треки, их EMA, заморозка кадра и
 * множество уже записанных id. Остальные экраны рисуются поверх абсолютным слоем, а камера
 * гасится флагом `активна` — заход в «Историю» не должен стоить пользователю всех треков.
 */
import React, { useEffect, useRef, useState } from 'react'
import { BackHandler, Pressable, StyleSheet, Text, View } from 'react-native'
import { добавить, записатьИсторию, прочитатьИсторию, type ЗаписьИстории } from './src/store/history'
import { создатьХранилище } from './src/store/mmkv'
import { НАСТРОЙКИ_ПО_УМОЛЧАНИЮ, прочитатьНастройки } from './src/store/settings'
import type { Хранилище } from './src/store/storage'
import { НАЧАЛЬНАЯ_НАВИГАЦИЯ, pop, push, верхний, type Экран } from './src/ui/navigation'
import CameraScreen from './src/ui/screens/CameraScreen'
import type { ПодписьТрека } from './src/vision/pipeline'

/**
 * Три состояния запуска, а не пара «готово/не готово». Отказ хранилища обязан быть виден:
 * иначе приложение, у которого не поднялся ключ Keystore, выглядит как приложение, которое
 * просто долго думает.
 */
type СостояниеЗапуска =
  | { вид: 'загрузка' }
  | { вид: 'готово'; хранилище: Хранилище; сброшен: boolean }
  | { вид: 'отказ'; текст: string }

/** Заголовки экранов-заглушек. Экраны появляются в задачах 14–15, навигация — уже здесь. */
const ЗАГОЛОВКИ: Record<Экран['вид'], string> = {
  камера: 'Камера',
  детали: 'Детали',
  история: 'История',
  настройки: 'Настройки',
}

export default function App(): React.JSX.Element {
  const [запуск, установитьЗапуск] = useState<СостояниеЗапуска>({ вид: 'загрузка' })
  const [навигация, установитьНавигацию] = useState(НАЧАЛЬНАЯ_НАВИГАЦИЯ)
  const [настройки, установитьНастройки] = useState(НАСТРОЙКИ_ПО_УМОЛЧАНИЮ)
  const [история, установитьИсторию] = useState<ЗаписьИстории[]>([])
  const [заморожено, установитьЗаморозку] = useState(false)

  // Подписи текущего кадра. Ref, а не состояние: они пересчитываются восемь раз в секунду,
  // и подъём их сюда перерисовывал бы всё дерево с той же частотой. Читает их экран
  // «Детали» (задача 14) — на замороженном кадре, где они уже не меняются.
  const подписиНаЭкране = useRef<ПодписьТрека[]>([])

  // Последний список, который уже лежит на диске. Нужен, чтобы не переписывать хранилище
  // тем же самым содержимым сразу после чтения при запуске.
  const историяНаДиске = useRef<ЗаписьИстории[] | null>(null)

  useEffect(() => {
    let живо = true
    создатьХранилище()
      .then(({ хранилище, сброшен }) => {
        if (!живо) return
        const прочитанная = сброшен ? [] : прочитатьИсторию(хранилище)
        историяНаДиске.current = прочитанная
        установитьНастройки(прочитатьНастройки(хранилище))
        установитьИсторию(прочитанная)
        установитьЗапуск({ вид: 'готово', хранилище, сброшен })
      })
      .catch((ошибка: unknown) => {
        if (живо) установитьЗапуск({ вид: 'отказ', текст: String(ошибка) })
      })
    return () => {
      живо = false
    }
  }, [])

  // Запись истории на диск — эффектом, а не внутри обновляющей функции `установитьИсторию`:
  // та обязана быть чистой, React вправе вызвать её дважды, и второй вызов дал бы вторую
  // запись в MMKV.
  useEffect(() => {
    if (запуск.вид !== 'готово') return
    if (историяНаДиске.current === история) return
    историяНаДиске.current = история
    записатьИсторию(запуск.хранилище, история)
  }, [запуск, история])

  useEffect(() => {
    const подписка = BackHandler.addEventListener('hardwareBackPress', () => {
      const назад = pop(навигация)
      // `false` отдаётся на дне стека намеренно: система закрывает приложение сама, а
      // перехват «назад» на камере превратил бы кнопку в заглушку.
      if (назад === null) return false
      установитьНавигацию(назад)
      return true
    })
    return () => подписка.remove()
  }, [навигация])

  if (запуск.вид === 'загрузка') {
    return (
      <View style={styles.экран}>
        <Text style={styles.текст}>Открываю хранилище…</Text>
      </View>
    )
  }

  if (запуск.вид === 'отказ') {
    return (
      <View style={styles.экран}>
        <Text style={styles.текст}>Хранилище не открылось: {запуск.текст}</Text>
      </View>
    )
  }

  const экран = верхний(навигация)

  const назад = (): void => {
    const состояние = pop(навигация)
    if (состояние !== null) установитьНавигацию(состояние)
  }

  return (
    <View style={styles.экран}>
      <CameraScreen
        настройки={настройки}
        заморожено={заморожено}
        активна={экран.вид === 'камера'}
        наЗаморозку={установитьЗаморозку}
        наТапПоТреку={(трек) => установитьНавигацию(push(навигация, { вид: 'детали', трек }))}
        наРаспознавание={(запись) => установитьИсторию((прежняя) => добавить(прежняя, запись))}
        подписиНаЭкране={подписиНаЭкране}
      />
      {экран.вид !== 'камера' && (
        <View style={[StyleSheet.absoluteFill, styles.поверхКамеры]}>
          {/*
            Заглушка до задач 14–15: навигация, аппаратная кнопка «назад» и гашение камеры
            проверяются уже сейчас, а содержимое экранов приезжает своими задачами.
          */}
          <Text style={styles.текст}>{ЗАГОЛОВКИ[экран.вид]}</Text>
          <Pressable onPress={назад}>
            <Text style={styles.кнопка}>Назад</Text>
          </Pressable>
        </View>
      )}
    </View>
  )
}

const styles = StyleSheet.create({
  экран: { flex: 1, alignItems: 'center', justifyContent: 'center', backgroundColor: '#000' },
  поверхКамеры: {
    alignItems: 'center',
    justifyContent: 'center',
    backgroundColor: '#000',
  },
  текст: { color: '#fff', fontSize: 18 },
  кнопка: { color: '#4da3ff', fontSize: 18, marginTop: 24 },
})
